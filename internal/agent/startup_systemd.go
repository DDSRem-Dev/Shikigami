package agent

import (
	"context"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	apb "github.com/DDSRem-Dev/Shikigami/pkg/protocol/agent"
)

func (p *startupObserver) systemd(ctx context.Context, result *apb.StartupPolicy) {
	result.Manager, result.ReasonCode = "systemd-user", "STARTUP_MANAGER_UNAVAILABLE"
	const properties = "LoadState,UnitFileState,FragmentPath,DropInPaths,NeedDaemonReload,Transient"
	data, err := p.run(ctx, "/usr/bin/systemctl", "--user", "show", "shiki-agent.service", "--no-pager", "--property="+properties)
	if err != nil {
		return
	}
	values, ok := startupProperties(data, "=")
	if !ok || len(values) != 6 {
		result.ReasonCode = "STARTUP_MANAGER_OUTPUT_UNKNOWN"
		return
	}
	path := filepath.Join(p.home, ".config/systemd/user/shiki-agent.service")
	unit, fileErr := p.read(path)
	if values["LoadState"] == "not-found" && values["FragmentPath"] == "" && values["DropInPaths"] == "" && os.IsNotExist(fileErr) {
		result.ManagedService, result.LoginStart, result.BootStart, result.ReasonCode = "absent", "disabled", "disabled", "STARTUP_MANAGED_SERVICE_ABSENT"
		return
	}
	result.ReasonCode = "STARTUP_SERVICE_CONFIGURATION_UNKNOWN"
	if fileErr != nil || values["LoadState"] != "loaded" || values["FragmentPath"] != path || values["DropInPaths"] != "" || values["NeedDaemonReload"] != "no" || values["Transient"] != "no" || !startupUnitMatches(unit, p.config) {
		return
	}
	// Re-read after querying the manager: a concurrent edit is not a stable policy
	// observation. NeedDaemonReload also prevents using stale loaded settings.
	again, err := p.run(ctx, "/usr/bin/systemctl", "--user", "show", "shiki-agent.service", "--no-pager", "--property="+properties)
	if err != nil || string(again) != string(data) {
		return
	}
	checked, err := p.read(path)
	if err != nil || string(checked) != string(unit) {
		return
	}
	switch values["UnitFileState"] {
	case "disabled":
		result.ManagedService, result.LoginStart, result.BootStart, result.ReasonCode = "present", "disabled", "disabled", "STARTUP_MANAGED_SERVICE_DISABLED"
	case "enabled":
		// is-enabled alone may refer to another target. Confirm the installer's
		// persistent default.target link rather than an enabled-runtime unit.
		link := filepath.Join(p.home, ".config/systemd/user/default.target.wants/shiki-agent.service")
		target, err := p.readlink(link)
		if err != nil {
			return
		}
		if !filepath.IsAbs(target) {
			target = filepath.Join(filepath.Dir(link), target)
		}
		if filepath.Clean(target) != path {
			return
		}
		result.ManagedService, result.LoginStart, result.ReasonCode = "present", "enabled", "STARTUP_LINGER_UNKNOWN"
		linger, err := p.run(ctx, "/usr/bin/loginctl", "show-user", strconv.FormatUint(uint64(p.uid), 10), "--property=Linger", "--value", "--no-pager")
		if err != nil {
			return
		}
		switch strings.TrimSpace(string(linger)) {
		case "yes":
			result.BootStart, result.ReasonCode = "enabled", "STARTUP_CONFIGURED_POLICY_OBSERVED"
		case "no":
			result.BootStart, result.ReasonCode = "disabled", "STARTUP_CONFIGURED_POLICY_OBSERVED"
		}
	}
}

func startupProperties(data []byte, separator string) (map[string]string, bool) {
	values := map[string]string{}
	for _, line := range strings.Split(strings.TrimSpace(string(data)), "\n") {
		key, value, ok := strings.Cut(line, separator)
		if !ok || key == "" {
			return nil, false
		}
		if _, exists := values[key]; exists {
			return nil, false
		}
		values[key] = value
	}
	return values, true
}

// Accept only the installer's bounded grammar. Unknown directives, drop-ins,
// specifiers and shell syntax stay unknown rather than being interpreted.
func startupUnitMatches(data []byte, configPath string) bool {
	if !strings.HasPrefix(string(data), "# Generated by shiki-install\n") {
		return false
	}
	section := ""
	seen := map[string]bool{}
	execMatches, targetMatches := false, false
	allowed := map[string]bool{"Unit.Description": true, "Unit.After": true, "Unit.Wants": true, "Service.Type": true, "Service.Environment": true, "Service.WorkingDirectory": true, "Service.ExecStart": true, "Service.Restart": true, "Service.RestartSec": true, "Service.TimeoutStopSec": true, "Service.UMask": true, "Service.NoNewPrivileges": true, "Service.StandardOutput": true, "Service.StandardError": true, "Service.KillMode": true, "Install.WantedBy": true}
	for _, line := range strings.Split(string(data), "\n") {
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if line == "[Unit]" || line == "[Service]" || line == "[Install]" {
			section = strings.Trim(line, "[]")
			continue
		}
		key, value, ok := strings.Cut(line, "=")
		name := section + "." + key
		if !ok || !allowed[name] || (seen[name] && name != "Service.Environment") {
			return false
		}
		expected := map[string]string{"Unit.Description": "Shikigami client", "Unit.After": "network-online.target", "Unit.Wants": "network-online.target", "Service.Type": "simple", "Service.WorkingDirectory": "~", "Service.Restart": "on-failure", "Service.RestartSec": "5s", "Service.TimeoutStopSec": "15s", "Service.UMask": "0077", "Service.NoNewPrivileges": "true", "Service.StandardOutput": "journal", "Service.StandardError": "journal", "Service.KillMode": "control-group"}
		if want, fixed := expected[name]; fixed && value != want {
			return false
		}
		seen[name] = true
		if name == "Service.Environment" {
			args, ok := startupUnitWords(value, false)
			if !ok || len(args) != 1 || (!strings.HasPrefix(args[0], "HOME=") && !strings.HasPrefix(args[0], "PATH=")) {
				return false
			}
		}
		if name == "Service.ExecStart" {
			args, ok := startupUnitArguments(value)
			execMatches = ok && len(args) == 3 && filepath.IsAbs(args[0]) && filepath.Base(args[0]) == "shiki-agent" && args[1] == "--config" && args[2] == configPath
		}
		if name == "Install.WantedBy" {
			targetMatches = value == "default.target"
		}
	}
	return execMatches && targetMatches
}

func startupUnitArguments(value string) ([]string, bool) { return startupUnitWords(value, true) }
func startupUnitWords(value string, expandDollar bool) ([]string, bool) {
	var args []string
	for value != "" {
		if value[0] != '"' {
			return nil, false
		}
		end := 1
		for end < len(value) {
			if value[end] == '\\' {
				end += 2
				continue
			}
			if value[end] == '"' {
				break
			}
			end++
		}
		if end >= len(value) {
			return nil, false
		}
		arg, err := strconv.Unquote(value[:end+1])
		if err != nil {
			return nil, false
		}
		// Generated units escape percent/dollar. Never expand user specifiers.
		if strings.Contains(strings.ReplaceAll(arg, "%%", ""), "%") || (expandDollar && strings.Contains(strings.ReplaceAll(arg, "$$", ""), "$")) {
			return nil, false
		}
		arg = strings.ReplaceAll(arg, "%%", "%")
		if expandDollar {
			arg = strings.ReplaceAll(arg, "$$", "$")
		}
		args = append(args, arg)
		value = value[end+1:]
		if value != "" {
			if value[0] != ' ' {
				return nil, false
			}
			value = value[1:]
		}
	}
	return args, true
}

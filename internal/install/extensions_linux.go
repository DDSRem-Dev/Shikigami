func installChromeKey(ctx context.Context, work string) error {
	ctx, cancel := context.WithTimeout(ctx, 30*time.Second)
	defer cancel()
	client := &http.Client{Timeout: 30 * time.Second, CheckRedirect: func(*http.Request, []*http.Request) error {
		return errors.New("Google signing key redirects are not accepted")
	}}
	request, err := http.NewRequestWithContext(ctx, http.MethodGet, chromeKeyURL, nil)
	if err != nil {
		return err
	}
	var data []byte
	err = ProgressStep(ctx, "Downloading the official Google signing key", func() error {
		response, err := client.Do(request)
		if err != nil {
			return err
		}
		defer response.Body.Close()
		if response.StatusCode != http.StatusOK || response.ContentLength > 1<<20 {
			return errors.New("invalid Google signing key response")
		}
		data, err = io.ReadAll(io.LimitReader(response.Body, (1<<20)+1))
		if err != nil || len(data) > 1<<20 {
			return errors.New("Google signing key is unreadable or oversized")
		}
		return nil
	})
	if err != nil {
		return err
	}
	home := filepath.Join(work, "gnupg")
	if err = os.Mkdir(home, 0700); err != nil {
		return err
	}
	key := filepath.Join(work, "google-key.asc")
	if err = os.WriteFile(key, data, 0600); err != nil {
		return err
	}
	listing, err := extensionCommand(ctx, "", "/usr/bin/gpg", "--batch", "--homedir", home, "--with-colons", "--import-options", "show-only", "--import", key)
	if err != nil {
		return err
	}
	primary, active := false, false
	for _, line := range strings.Split(string(listing), "\n") {
		fields := strings.Split(line, ":")
		if len(fields) < 10 {
			continue
		}
		if fields[0] == "pub" {
			primary = true
			continue
		}
		if fields[0] == "sub" {
			primary = false
		}
		if primary && fields[0] == "fpr" {
			if fields[9] == chromeKeyFingerprint {
				active = true
			} else if fields[9] != "4CCA1EAF950CEE4AB83976DCA040830F7FAC5991" {
				return errors.New("unrecognized Google primary signing key; administrator must review provenance")
			}
			primary = false
		}
	}
	if !active {
		return errors.New("Google key does not contain the independently pinned active primary fingerprint")
	}
	if err = extensionRun(ctx, "", "/usr/bin/gpg", "--batch", "--homedir", home, "--import", key); err != nil {
		return err
	}
	keyring := filepath.Join(work, "chrome.gpg")
	if err = extensionRun(ctx, "", "/usr/bin/gpg", "--batch", "--homedir", home, "--output", keyring, "--export", chromeKeyFingerprint); err != nil {
		return err
	}
	data, err = readRegular(work, "chrome.gpg", 1<<20)
	if err != nil || len(data) == 0 {
		return errors.New("could not export pinned Google signing key")
	}
	return writeRootFile(chromeKeyPath, data, 0644, false)
}

func maintainChrome(ctx context.Context, work string, update bool) error {
	if update {
		status, err := extensionCommand(ctx, "", "/usr/bin/dpkg-query", "-W", "-f=${Status}", "google-chrome-stable")
		if err != nil || strings.TrimSpace(string(status)) != "install ok installed" {
			return errors.New("Chrome is not installed; use explicit setup rather than maintenance")
		}
	}
	if err := installChromeKey(ctx, work); err != nil {
		return err
	}
	if err := writeRootFile(chromeSourcePath, []byte(chromeSource(runtime.GOARCH)), 0644, true); err != nil {
		return err
	}
	if err := configureChromeDefaults(); err != nil {
		return err
	}
	// APT owns partial/ as _apt; only its protected list parent is ours.
	if err := systemBinDirectory("/var/lib/shikigami-install/apt-chrome/lists"); err != nil {
		return err
	}
	if err := extensionRun(ctx, "", "/usr/bin/apt-get", append(chromeAPTArgs(), "update")...); err != nil {
		return err
	}
	policy, err := extensionCommand(ctx, "", "/usr/bin/apt-cache", append(chromeAPTArgs(), "policy", "google-chrome-stable")...)
	if err != nil {
		return err
	}
	candidate := ""
	for _, line := range strings.Split(string(policy), "\n") {
		if strings.HasPrefix(strings.TrimSpace(line), "Candidate:") {
			candidate = strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(line), "Candidate:"))
		}
	}
	if candidate == "" || candidate == "(none)" || !regexp.MustCompile(`^[0-9][A-Za-z0-9.+:~_-]{0,127}$`).MatchString(candidate) || !strings.Contains(string(policy), "https://dl.google.com/linux/chrome/deb") {
		return errors.New("no authenticated official stable Chrome candidate for this architecture; no fallback is permitted")
	}
	download := filepath.Join(work, "chrome-package")
	if err = os.Mkdir(download, 0700); err != nil {
		return err
	}
	if err = extensionRun(ctx, download, "/usr/bin/apt-get", append(chromeAPTArgs(), "download", "google-chrome-stable="+candidate)...); err != nil {
		return err
	}
	entries, err := os.ReadDir(download)
	if err != nil || len(entries) != 1 {
		return errors.New("expected one authenticated Chrome package")
	}
	path := filepath.Join(download, entries[0].Name())
	info, err := os.Lstat(path)
	if err != nil || !info.Mode().IsRegular() || !strings.HasSuffix(path, ".deb") {
		return errors.New("unsafe downloaded Chrome package")
	}
	fields, err := extensionCommand(ctx, "", "/usr/bin/dpkg-deb", "--field", path, "Package", "Version", "Architecture")
	if err != nil {
		return err
	}
	values := map[string]string{}
	for _, line := range strings.Split(string(fields), "\n") {
		key, value, ok := strings.Cut(line, ":")
		if ok {
			values[key] = strings.TrimSpace(value)
		}
	}
	if values["Package"] != "google-chrome-stable" || values["Version"] != candidate || values["Architecture"] != runtime.GOARCH {
		return errors.New("authenticated Chrome package identity mismatch")
	}
	return extensionRun(ctx, "", "/usr/bin/apt-get", "install", "--no-install-recommends", "--yes", path)
}

func applyExtensionPlan(ctx context.Context, operation string, o ExtensionOptions) error {
	var plan *ExtensionPlan
	err := ProgressStep(ctx, "Checking the approved system-support plan", func() error {
		var err error
		plan, err = ExtensionPlatformPlan(ctx, operation, o)
		return err
	})
	if err != nil {
		return err
	}
	if err = extensionBlocked(plan); err != nil {
		return err
	}
	if operation == "maintenance" && !o.Update && !o.BootUnlock {
		return nil
	}
	if !o.StageOnly && os.Geteuid() != 0 {
		return errors.New("applying dependencies/helper authorization requires root; the daemon, plugin and Chrome must remain ordinary-user processes")
	}
	if err = lockRootCredentialCoreDumps(o); err != nil {
		return err
	}
	if err = ensureSystemPrefix("/var/tmp"); err != nil {
		return err
	}
	work, err := os.MkdirTemp("/var/tmp", "shiki-extension-install-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(work)
	if !o.StageOnly {
		unlock, err := lockExtensionInstallation()
		if err != nil {
			return err
		}
		defer unlock()
	}
	var bundle *Bundle
	var verified releaseauth.Verified
	if operation == "setup" {
		err = ProgressStep(ctx, "Verifying and extracting signed system support", func() error {
			var err error
			bundle, verified, err = verifiedExtensionBundle(ctx, o, work)
			return err
		})
		if err != nil {
			return err
		}
		if o.StageOnly {
			return stageExtensionSupport(bundle, o, plan, verified)
		}
		if err = checkRegionInstallationUID(o, plan.UID); err != nil {
			return err
		}
	}
	if operation == "setup" || o.Update {
		if err = extensionRun(ctx, "", "/usr/bin/apt-get", "-o", "APT::Update::Error-Mode=any", "update"); err != nil {
			return err
		}
		args := []string{"install", "--no-install-recommends", "--yes"}
		if operation == "maintenance" {
			args = append(args, "--only-upgrade")
		}
		if err = extensionRun(ctx, "", "/usr/bin/apt-get", append(args, plan.Packages...)...); err != nil {
			return err
		}
		if operation == "setup" {
			if err = ensureExtensionLocales(); err != nil {
				return err
			}
			if err = extensionRun(ctx, "", "/usr/sbin/locale-gen"); err != nil {
				return err
			}
		}
		if o.includes("browser") {
			if err = maintainChrome(ctx, work, operation == "maintenance"); err != nil {
				return err
			}
			if err = installChromeManagedPolicy(plan); err != nil {
				return err
			}
			if operation == "setup" {
				if err = installBrowserRuntimeSupport(ctx, bundle, plan, verified); err != nil {
					return err
				}
				if err = extensionRun(ctx, "", "/usr/bin/loginctl", "enable-linger", strconv.Itoa(plan.UID)); err != nil {
					return err
				}
				if err = extensionRun(ctx, "", "/usr/bin/systemctl", "start", "user@"+strconv.Itoa(plan.UID)+".service"); err != nil {
					return err
				}
			}
		}
	}
	if o.BootUnlock {
		if err = installBootUnlock(ctx, plan, o, work); err != nil {
			return err
		}
	}
	if operation == "setup" && o.includes("region") {
		if err = installRegionSupport(ctx, bundle, plan, verified, work); err != nil {
			return err
		}
	}
	return recordExtensionReceipt(plan, bundle, verified, o)
}

func checkRegionInstallationUID(o ExtensionOptions, uid int) error {
	if !o.includes("region") {
		return nil
	}
	data, err := readRegular("/etc", filepath.Base(RegionPolicyPath), 64<<10)
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil {
		return err
	}
	info, err := os.Lstat(RegionPolicyPath)
	if err != nil {
		return err
	}
	owner, ok := info.Sys().(*syscall.Stat_t)
	if !ok || owner.Uid != 0 || !info.Mode().IsRegular() || info.Mode().Perm() != 0600 {
		return errors.New("existing region policy must be root-owned mode 0600")
	}
	var policy struct {
		DaemonUID  int `json:"daemon_uid"`
		PlanTTL    int `json:"plan_ttl_seconds"`
		DNSConfirm int `json:"dns_confirm_seconds"`
	}
	if err = decode(data, &policy); err != nil {
		return err
	}
	if policy.DaemonUID != uid {
		return errors.New("region helper is already authorized for a different UID; revoke and review root policy/evidence before reassigning")
	}
	if policy.PlanTTL < 30 || policy.PlanTTL > 900 || policy.DNSConfirm < 30 || policy.DNSConfirm > 600 {
		return errors.New("existing region policy has invalid lease bounds")
	}
	return nil
}

func installRegionSupport(ctx context.Context, bundle *Bundle, plan *ExtensionPlan, verified releaseauth.Verified, work string) error {
	uid := plan.UID
	if err := copyExtensionBinary(bundle, "shiki-region-helper", RegionHelperPath); err != nil {
		return err
	}
	if err := recordExtensionReceipt(plan, bundle, verified, ExtensionOptions{Component: "region"}); err != nil {
		return err
	}
	if err := ensureSystemPrefix(RegionStatePath); err != nil {
		return err
	}
	if err := privateOwnedDir(RegionStatePath, 0, 0); err != nil {
		return err
	}
	if _, err := os.Lstat(RegionPolicyPath); errors.Is(err, os.ErrNotExist) {
		policy, _ := json.Marshal(map[string]int{"daemon_uid": uid, "plan_ttl_seconds": 300, "dns_confirm_seconds": 120})
		if err := writeRootFile(RegionPolicyPath, append(policy, '\n'), 0600, false); err != nil {
			return err
		}
	} else if err != nil {
		return err
	}
	sudoers := []byte(regionSudoers(uid))
	staged := filepath.Join(work, "region.sudoers")
	if err := os.WriteFile(staged, sudoers, 0600); err != nil {
		return err
	}
	if err := extensionRun(ctx, "", "/usr/sbin/visudo", "--check", "--file", staged); err != nil {
		return err
	}
	if err := writeRootFile("/etc/systemd/system/"+RegionGuardUnit, []byte(regionGuardService()), 0644, true); err != nil {
		return err
	}
	if err := extensionRun(ctx, "", "/usr/bin/systemctl", "daemon-reload"); err != nil {
		return err
	}
	status, err := callInstalledRegionHelper(ctx, "activate")
	if err != nil {
		return err
	}
	if status.State != "ready" || status.PendingOperationID != "" {
		return fmt.Errorf("region helper activation requires administrator recovery review (state=%s pending=%s)", status.State, status.PendingOperationID)
	}
	if err = extensionRun(ctx, "", "/usr/bin/systemctl", "enable", RegionGuardUnit); err != nil {
		return err
	}
	if err = extensionRun(ctx, "", "/usr/bin/systemctl", "restart", RegionGuardUnit); err != nil {
		return err
	}
	if err = writeRootFile("/etc/sudoers.d/shikigami-region-"+strconv.Itoa(uid), sudoers, 0440, true); err != nil {
		return err
	}
	return installRegionDaemonPolicy(ctx, plan.User, uid)
}

func (n *Native) removeInstalledExtensions(ctx context.Context, plan Plan) error {
	if plan.Role != "daemon" {
		return nil
	}
	_, uid, _, err := accountFor(plan)
	if err != nil {
		return err
	}
	unlock, err := lockExtensionInstallation()
	if err != nil {
		return err
	}
	defer unlock()
	if err = revokeRegionGrant(uid); err != nil {
		return err
	}
	// Host-owned offline disable takes the daemon and plugin-control state locks
	// as the ordinary UID. Refuse cleanup if a manual/live host still owns them.
	if err = n.userLayoutCall(ctx, plan, "disable-browser"); err != nil {
		return err
	}
	if err = stopInstalledBrowserUnits(ctx, plan); err != nil {
		return err
	}
	if err = n.removeRegionSupport(ctx, plan, uid); err != nil {
		return err
	}
	if err = removeBootUnlock(ctx, plan, uid); err != nil {
		return err
	}
	if err = removeBrowserSupport(ctx, plan); err != nil {
		return err
	}
	return removeChromeManagedPolicy()
}

func stopInstalledBrowserUnits(ctx context.Context, plan Plan) error {
	_, err := installedBrowserUnits(ctx, plan, true)
	return err
}

func installedBrowserUnits(ctx context.Context, plan Plan, stop bool) (bool, error) {
	ctx, cancel := context.WithTimeout(ctx, 45*time.Second)
	defer cancel()
	_, uid, _, err := accountFor(plan)
	if err != nil {
		return false, err
	}
	if _, err = os.Stat("/run/user/" + strconv.Itoa(uid) + "/bus"); errors.Is(err, os.ErrNotExist) {
		return false, nil
	} else if err != nil {
		return false, err
	}
	cmd := command(ctx, plan, true, "/usr/bin/systemctl", "--user", "list-units", "--all", "--plain", "--no-legend", "--no-pager", "shiki-browser-*.service")
	captured := &cappedOutput{limit: 64 << 10}
	cmd.Stdout, cmd.Stderr = captured, io.Discard
	if err = cmd.Run(); err != nil {
		return false, fmt.Errorf("could not enumerate managed browser units: %w", err)
	}
	data, truncated := captured.Bytes()
	if truncated {
		return false, errors.New("browser unit listing exceeds bound")
	}
	running := false
	for _, line := range strings.Split(string(data), "\n") {
		fields := strings.Fields(line)
		if len(fields) == 0 {
			continue
		}
		unit := fields[0]
		if len(fields) < 4 || !browserUnitName.MatchString(unit) {
			return false, errors.New("unexpected browser runtime unit listing")
		}
		if !stop && (fields[2] == "inactive" || fields[2] == "failed") {
			continue
		}
		show := command(ctx, plan, true, "/usr/bin/systemctl", "--user", "show", unit, "--property=Description,ExecStart")
		identity := &cappedOutput{limit: 64 << 10}
		show.Stdout, show.Stderr = identity, io.Discard
		if err = show.Run(); err != nil {
			return false, fmt.Errorf("could not verify browser unit identity: %w", err)
		}
		details, cut := identity.Bytes()
		if cut {
			return false, errors.New("browser unit identity exceeds bound")
		}
		description, executable := false, false
		for _, line := range strings.Split(string(details), "\n") {
			if strings.HasPrefix(line, "Description=ShikigamiBrowser:") && len(strings.TrimPrefix(line, "Description=ShikigamiBrowser:")) > 0 {
				description = true
			}
			if strings.HasPrefix(line, "ExecStart=") && strings.Contains(line, "path="+BrowserRuntimePath+" ;") {
				executable = true
			}
		}
		if !description || !executable {
			return false, fmt.Errorf("unrecognized browser unit identity %s", unit)
		}
		running = true
		if stop {
			if err = run(ctx, plan, true, "/usr/bin/systemctl", "--user", "stop", unit); err != nil {
				return false, err
			}
		}
	}
	return running, nil
}

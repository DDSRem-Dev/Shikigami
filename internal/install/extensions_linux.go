func extensionPackages(o ExtensionOptions) []string {
	var packages []string
	seen := map[string]bool{}
	for _, group := range []struct {
		enabled bool
		names   []string
	}{{o.includes("region"), regionPackages}, {o.includes("browser"), browserPackages}} {
		if group.enabled {
			for _, name := range group.names {
				if !seen[name] {
					packages = append(packages, name)
					seen[name] = true
				}
			}
		}
	}
	return packages
}

func extensionOSRelease(root string) (string, string, error) {
	var data []byte
	var err error
	for _, directory := range []string{"etc", "usr/lib"} {
		data, err = readRegular(filepath.Join("/", root, directory), "os-release", 64<<10)
		if err == nil {
			break
		}
	}
	if err != nil {
		return "", "", err
	}
	values := map[string]string{}
	for _, line := range strings.Split(string(data), "\n") {
		key, value, ok := strings.Cut(line, "=")
		if ok && (key == "ID" || key == "VERSION_ID") {
			if _, duplicate := values[key]; duplicate {
				return "", "", errors.New("duplicate OS release field")
			}
			values[key] = strings.Trim(value, `"'`)
		}
	}
	return values["ID"], values["VERSION_ID"], nil
}


func extensionPlatformPlan(ctx context.Context, operation string, o ExtensionOptions) (*ExtensionPlan, error) {
	plan := &ExtensionPlan{Operation: operation, Component: o.Component, Platform: runtime.GOOS + "/" + runtime.GOARCH, User: o.User, StageOnly: o.StageOnly, RootPrefix: o.RootPrefix, Packages: extensionPackages(o), InstalledVersions: map[string]string{}}
	account, err := user.Lookup(o.User)
	if err != nil {
		return nil, err
	}
	uid, err := strconv.Atoi(account.Uid)
	if err != nil || uid == 0 {
		return nil, errors.New("an existing non-root runtime user is required")
	}
	plan.UID = uid
	id, release, err := extensionOSRelease(o.RootPrefix)
	plan.Distribution = id + " " + release
	if err != nil || !((id == "ubuntu" && release == "24.04") || (id == "debian" && release == "12")) {
		plan.Blocked = append(plan.Blocked, "requires Ubuntu 24.04 or Debian 12")
	}
	if runtime.GOARCH != "amd64" && runtime.GOARCH != "arm64" {
		plan.Blocked = append(plan.Blocked, "requires amd64 or arm64")
	}
	if !o.StageOnly {
		if _, err := os.Stat("/run/systemd/system"); err != nil {
			plan.Blocked = append(plan.Blocked, "systemd must be running")
		}
		for _, pkg := range append(append([]string{}, plan.Packages...), "google-chrome-stable") {
			output, err := extensionCommand(ctx, "", "/usr/bin/dpkg-query", "-W", "-f=${Status}\t${Version}\t${Architecture}", pkg)
			if err != nil {
				plan.InstalledVersions[pkg] = "not installed or version unavailable"
			} else {
				plan.InstalledVersions[pkg] = strings.TrimSpace(string(output))
			}
		}
		receipt, receiptErr := readExtensionReceipt()
		for _, support := range []struct{ component, name, path string }{{"region", "shiki-region-helper", RegionHelperPath}, {"browser", "shiki-browser-runtime", BrowserRuntimePath}} {
			if !o.includes(support.component) {
				continue
			}
			if _, err := os.Lstat(support.path); errors.Is(err, os.ErrNotExist) {
				plan.InstalledVersions[support.name] = "not installed"
			} else if err != nil || receiptErr != nil || receipt == nil || receipt.SignedReleases[support.name].Version == "" {
				plan.InstalledVersions[support.name] = "version unknown; protected signed-payload receipt unavailable"
			} else {
				plan.InstalledVersions[support.name] = "signed install receipt: " + receipt.SignedReleases[support.name].Version + " (inspection does not execute support binaries)"
			}
		}
		if operation == "maintenance" && o.Update && o.includes("browser") && !strings.HasPrefix(plan.InstalledVersions["google-chrome-stable"], "install ok installed\t") {
			plan.Blocked = append(plan.Blocked, "Chrome stable is not installed; use explicit setup rather than maintenance")
		}
	}
	plan.Sources = []string{"Existing administrator-managed Ubuntu/Debian APT sources for distribution dependencies (not changed by this installer).", "Local signed Shikigami release: independent root-owned Ed25519 public key -> authenticated archive -> signed SHA256SUMS pin -> payload hash while copying. No root code executes from a writable user plugin directory."}
	plan.Warnings = []string{"PLAN ONLY unless --yes is supplied; version detection does not use the public network.", "APT changes are not transactional and installed/upgraded packages are never automatically rolled back or purged.", "No existing tmux, Claude, Chrome or browser runtime is restarted; host automatic-update policy is not changed.", "Uninstall preserves browser profiles and region snapshots/journal. It first revokes helper grants and quiesces the trusted installed helper; pending/conflicted recovery blocks uninstall and retains the guard/helper/policy. Only a clean disabled status permits removing recovery code."}
	plan.Paths = []string{extensionReceiptPath}
	if operation == "setup" {
		appendPublicSupportDirectoryPlan(plan, o)
	}
	if o.includes("region") {
		plan.Paths = append(plan.Paths, RegionHelperPath, RegionPolicyPath, RegionStatePath, "/etc/sudoers.d/shikigami-region-"+strconv.Itoa(uid), "/etc/systemd/system/"+RegionGuardUnit, regionDaemonDropIn)
		plan.Warnings = append(plan.Warnings, "Explicit region support installs a daemon-only NoNewPrivileges=false drop-in so its ordinary UID can use the six-action sudoers grant. An already-running managed daemon with NoNewPrivs=1 is restarted; independent tmux, Claude and Chrome remain running. Core-only installations retain NoNewPrivileges=true.")
		if !o.StageOnly && operation == "setup" {
			if _, err := inspectRegionDaemonPolicy(plan.User, uid); err != nil {
				plan.Blocked = append(plan.Blocked, err.Error())
			}
		}
		plan.Warnings = append(plan.Warnings, "Region authorization is for this one daemon UID; any process of that UID can invoke the six allowlisted actions. The root guard is never granted in sudoers.")
		for _, action := range []string{"inspect", "plan", "apply", "confirm", "rollback", "operation"} {
			plan.Authorization = append(plan.Authorization, ExtensionCommand{Program: RegionHelperPath, Args: []string{action}, AsUser: plan.User})
		}
	}
	if o.includes("browser") {
		plan.Paths = append(plan.Paths, BrowserRuntimePath, BrowserRuntimeInstallLock, chromeKeyPath, chromeSourcePath, chromeDefaultsPath, chromePolicyPath)
		plan.Sources = append(plan.Sources, "Google official stable APT: https://dl.google.com/linux/chrome/deb/ stable main; package google-chrome-stable for "+runtime.GOARCH+".", "Google official signing key "+chromeKeyURL+"; primary fingerprint "+chromeKeyFingerprint+" (https://www.google.com/linuxrepositories/). Only this primary and its certified subkeys are exported to a source-scoped Signed-By keyring.")
		plan.Warnings = append(plan.Warnings, "Chrome ARM64 was announced for Q2 2026; actual signed stable package availability is checked after administrator-approved refresh. Missing packages fail; never substitute Chromium or an unofficial build.", "Headless private DBus/IME uses fcitx5 pinyin+mozc, TigerVNC and openbox. GNOME secret service requires a user-provisioned unlocked encrypted keyring; setup never creates an empty-password keyring or enables plaintext storage. Browser startup must report this gate.", "Explicit setup enables linger for the selected user and starts its private systemd user manager. It does not start Chrome or enable a browser profile.", "The fixed Chrome source/keyring are created only after --yes. A different unmanaged source at the fixed path blocks setup. Existing Chrome defaults and update policies are preserved unchanged; only a fresh absent defaults file gets repo_add_once=false and repo_reenable_on_distupgrade=false. Chrome's maintainer scripts may preserve/manage their own official source at /etc/apt/sources.list.d/google-chrome.list; no alternate source is silently accepted.")
		plan.Warnings = append(plan.Warnings, "Secret-service uses the existing private user bus unless explicit administrator boot-unlock policy selects a dedicated private bus. IME remains on its own DBus; user session IME and telemetry settings are not replaced.", "Changed runtime payload publication requires explicitly stopped managed Chrome and no pending start jobs; the permanent root-owned installation lock serializes launch/publication, and identical binaries retain their inode.")
		plan.Warnings = append(plan.Warnings, "MANDATORY MACHINE-WIDE CHROME POLICY: PasswordManagerEnabled=false, SyncDisabled=true, BrowserSignin=0. This affects every Chrome user/profile on this host and existing Chrome may refresh policies without restarting. Other managed policies are preserved; conflicting or unverifiable policy blocks browser setup. Uninstall removes only this policy file if this installer created it, after managed browsers stop.")
		if err := inspectChromeManagedPolicies(o.RootPrefix, o.StageOnly); err != nil {
			plan.Blocked = append(plan.Blocked, err.Error())
		}
	}
	if o.BootUnlock {
		if err := appendBootUnlockPlan(ctx, plan, o, account); err != nil {
			return nil, err
		}
	}
	if operation == "setup" {
		if o.Bundle == "" || o.Archive == "" || o.Signature == "" || o.PublicKey == "" || !releaseVersion.MatchString(o.Version) {
			plan.Blocked = append(plan.Blocked, "setup requires --bundle, --archive, --signature, --public-key and fixed --version")
		}
		if o.StageOnly && o.RootPrefix == "" {
			plan.Blocked = append(plan.Blocked, "stage-only setup requires --root-prefix for an inert fixture")
		}
		if !o.StageOnly {
			plan.Commands = append(plan.Commands, ExtensionCommand{Program: "/usr/bin/apt-get", Args: []string{"-o", "APT::Update::Error-Mode=any", "update"}, Network: true}, ExtensionCommand{Program: "/usr/bin/apt-get", Args: append([]string{"install", "--no-install-recommends", "--yes"}, plan.Packages...), Network: true}, ExtensionCommand{Program: "/usr/sbin/locale-gen", Args: []string{}, Network: false})
			plan.Warnings = append(plan.Warnings, "Add only missing en_US.UTF-8, ja_JP.UTF-8 and zh_CN.UTF-8 entries to /etc/locale.gen; generate them without changing the machine default locale/timezone/DNS.")
		}
	} else if o.Update {
		plan.Commands = append(plan.Commands, ExtensionCommand{Program: "/usr/bin/apt-get", Args: []string{"-o", "APT::Update::Error-Mode=any", "update"}, Network: true}, ExtensionCommand{Program: "/usr/bin/apt-get", Args: append([]string{"install", "--only-upgrade", "--no-install-recommends", "--yes"}, plan.Packages...), Network: true})
		plan.Warnings = append(plan.Warnings, "Explicit stable maintenance upgrades only installed allowlisted dependencies; support binary upgrades require setup with a new signed release. It never restarts a running Chrome; the installed Chrome version takes effect at the next explicit browser start.")
	}
	if !o.StageOnly && o.includes("browser") && (operation == "setup" || o.Update) {
		plan.Commands = append(plan.Commands, ExtensionCommand{Program: "HTTPS GET", Args: []string{chromeKeyURL, "verify primary fingerprint " + chromeKeyFingerprint}, Network: true}, ExtensionCommand{Program: "/usr/bin/apt-get", Args: append(chromeAPTArgs(), "update"), Network: true}, ExtensionCommand{Program: "/usr/bin/apt-get", Args: append(chromeAPTArgs(), "download", "google-chrome-stable=<authenticated-stable-candidate>"), Network: true}, ExtensionCommand{Program: "/usr/bin/apt-get", Args: []string{"install", "--no-install-recommends", "--yes", "<root-private-authenticated-google-chrome-stable.deb>"}, Network: true})
		if operation == "setup" {
			plan.Commands = append(plan.Commands, ExtensionCommand{Program: "/usr/bin/loginctl", Args: []string{"enable-linger", account.Uid}}, ExtensionCommand{Program: "/usr/bin/systemctl", Args: []string{"start", "user@" + account.Uid + ".service"}})
		}
	}
	if !o.StageOnly && o.includes("region") && operation == "setup" {
		plan.Commands = append(plan.Commands, ExtensionCommand{Program: "/usr/sbin/visudo", Args: []string{"--check", "--file", "<private-staged-sudoers>"}}, ExtensionCommand{Program: RegionHelperPath, Args: []string{"activate"}}, ExtensionCommand{Program: "/usr/bin/systemctl", Args: []string{"daemon-reload"}}, ExtensionCommand{Program: "/usr/bin/systemctl", Args: []string{"enable", RegionGuardUnit}}, ExtensionCommand{Program: "/usr/bin/systemctl", Args: []string{"restart", RegionGuardUnit}})
		plan.Commands = append(plan.Commands, ExtensionCommand{Program: "/usr/bin/systemctl", Args: []string{"daemon-reload"}}, ExtensionCommand{Program: "/usr/bin/systemctl", Args: []string{"show", "shiki-daemon.service", "--property=User", "--property=NoNewPrivileges", "--property=MainPID"}}, ExtensionCommand{Program: "/usr/bin/systemctl", Args: []string{"try-restart", "shiki-daemon.service"}})
		plan.Warnings = append(plan.Warnings, "The root recovery guard is explicitly started/restarted after signed helper activation; the six-action sudoers grant is published only after this succeeds. Running Chrome and ordinary host processes are not restarted.")
	}
	return plan, nil
}

func extensionCommand(ctx context.Context, directory, binary string, args ...string) ([]byte, error) {
	return extensionExec(ctx, directory, binary, true, args...)
}

func extensionRun(ctx context.Context, directory, binary string, args ...string) error {
	return ProgressStep(ctx, extensionProgressLabel(binary, args), func() error {
		_, err := extensionExec(ctx, directory, binary, false, args...)
		return err
	})
}

// Labels are fixed text, never command arguments or captured subprocess output.
func extensionProgressLabel(binary string, args []string) string {
	switch binary {
	case "/usr/bin/apt-get":
		for _, arg := range args {
			switch arg {
			case "update":
				return "Refreshing package indexes (network access may take several minutes)"
			case "download":
				return "Downloading authenticated Google Chrome"
			case "install":
				return "Installing system packages (downloads and configuration may take several minutes)"
			}
		}
	case "/usr/sbin/locale-gen":
		return "Generating language locales"
	case "/usr/bin/systemctl":
		for _, arg := range args {
			if strings.HasPrefix(arg, "shikigami-browser-keyring-provision-") {
				return "Creating and verifying the encrypted browser keyring service"
			}
			if strings.HasPrefix(arg, "shikigami-browser-keyring-") {
				return "Configuring unattended browser keyring unlock"
			}
		}
		return "Configuring and checking system services"
	case "/usr/bin/loginctl":
		return "Enabling the ordinary user's background service manager"
	case "/usr/bin/gpg":
		return "Preparing the verified Google package signing key"
	case "/usr/bin/systemd-creds":
		return "Preparing host encryption for unattended keyring unlock"
	case "/usr/sbin/visudo":
		return "Validating restricted region helper authorization"
	}
	return "Applying system support"
}

// Parsed output must be complete. Verbose package/service command success is
// determined by its exit status, while diagnostics remain bounded in memory.
func extensionExec(ctx context.Context, directory, binary string, complete bool, args ...string) ([]byte, error) {
	ctx, cancel := context.WithTimeout(ctx, 20*time.Minute)
	defer cancel()
	cmd := exec.CommandContext(ctx, binary, args...)
	cmd.Dir = directory
	cmd.WaitDelay = time.Second
	cmd.Env = []string{"PATH=/usr/sbin:/usr/bin:/sbin:/bin", "HOME=/root", "LANG=C.UTF-8", "DEBIAN_FRONTEND=noninteractive", "NEEDRESTART_MODE=l"}
	captured := &cappedOutput{limit: 64 << 10}
	cmd.Stdout, cmd.Stderr = captured, captured
	err := cmd.Run()
	data, truncated := captured.Bytes()
	if complete && truncated && err == nil {
		return nil, fmt.Errorf("%s output exceeds 64 KiB", filepath.Base(binary))
	}
	if err != nil {
		return nil, fmt.Errorf("%s failed: %w (%s)", filepath.Base(binary), err, strings.TrimSpace(string(data[:min(len(data), 2048)])))
	}
	return data, nil
}

func trustedExtensionKey(path string, stage bool) error {
	if !filepath.IsAbs(path) {
		return errors.New("independent public key path must be absolute")
	}
	info, err := os.Lstat(path)
	if err != nil {
		return err
	}
	stat, ok := info.Sys().(*syscall.Stat_t)
	if !ok || !info.Mode().IsRegular() || info.Mode().Perm()&0022 != 0 || info.Size() > releaseauth.MaxMetadataBytes {
		return errors.New("unsafe public trust key")
	}
	if stage {
		if stat.Uid != uint32(os.Geteuid()) {
			return errors.New("staging trust key must be owned by the staging user")
		}
		return nil
	}
	if stat.Uid != 0 {
		return errors.New("production public trust key must be independently provisioned by root")
	}
	for parent := filepath.Dir(path); ; parent = filepath.Dir(parent) {
		info, err = os.Lstat(parent)
		if err != nil {
			return err
		}
		stat, ok = info.Sys().(*syscall.Stat_t)
		if !ok || !info.IsDir() || stat.Uid != 0 || info.Mode().Perm()&0022 != 0 {
			return errors.New("public trust key ancestors must be root-owned, non-symlink and not writable by other users")
		}
		if parent == "/" {
			break
		}
	}
	return nil
}

func verifiedExtensionBundle(ctx context.Context, o ExtensionOptions, work string) (*Bundle, releaseauth.Verified, error) {
	var empty releaseauth.Verified
	if err := trustedExtensionKey(o.PublicKey, o.StageOnly); err != nil {
		return nil, empty, err
	}
	verified, err := releaseauth.Verify(ctx, releaseauth.VerifyOptions{Archive: o.Archive, Signature: o.Signature, PublicKey: o.PublicKey, Output: filepath.Join(work, "verified"), Version: o.Version, OS: runtime.GOOS, Arch: runtime.GOARCH})
	if err != nil {
		return nil, empty, err
	}
	bundle, err := Verify(o.Bundle, o.Version, verified.ChecksumsSHA256)
	if err != nil {
		return nil, empty, err
	}
	for _, support := range []struct{ component, name string }{{"region", "shiki-region-helper"}, {"browser", "shiki-browser-runtime"}} {
		if o.includes(support.component) && !bundle.Manifest.Has(support.name) {
			return nil, empty, fmt.Errorf("signed release does not contain %s; old releases remain installable but cannot provision missing optional support", support.name)
		}
	}
	return bundle, verified, nil
}

func writeRootFile(path string, data []byte, mode os.FileMode, managed bool) error {
	if err := systemBinDirectory(filepath.Dir(path)); err != nil {
		return err
	}
	info, err := os.Lstat(path)
	if err == nil {
		owner, ok := info.Sys().(*syscall.Stat_t)
		if !ok || !info.Mode().IsRegular() || owner.Uid != 0 || info.Mode().Perm()&0022 != 0 {
			return errors.New("refusing unsafe root installation destination")
		}
		current, err := readRegular(filepath.Dir(path), filepath.Base(path), 1<<20)
		if err != nil {
			return err
		}
		if bytes.Equal(current, data) && info.Mode().Perm() == mode {
			return nil
		}
		if managed && !bytes.Contains(current, []byte("Generated by shiki-install")) {
			return fmt.Errorf("refusing to replace unmanaged file %s", path)
		}
	} else if !errors.Is(err, os.ErrNotExist) {
		return err
	}
	root, err := os.OpenRoot(filepath.Dir(path))
	if err != nil {
		return err
	}
	defer root.Close()
	return atomicExtensionFile(root, filepath.Base(path), data, mode)
}

func atomicExtensionFile(root *os.Root, name string, data []byte, mode os.FileMode) error {
	temp := ".shiki-" + strconv.FormatInt(time.Now().UnixNano(), 16)
	file, err := root.OpenFile(temp, os.O_CREATE|os.O_EXCL|os.O_WRONLY|syscall.O_NOFOLLOW, mode)
	if err != nil {
		return err
	}
	defer root.Remove(temp)
	if os.Geteuid() == 0 {
		err = file.Chown(0, 0)
	}
	if err == nil {
		err = file.Chmod(mode)
	}
	if err == nil {
		_, err = file.Write(data)
	}
	if err == nil {
		err = file.Sync()
	}
	err = errors.Join(err, file.Close())
	if err != nil {
		return err
	}
	if err = root.Rename(temp, name); err != nil {
		return err
	}
	return syncDir(root)
}

func copyExtensionBinary(bundle *Bundle, name, target string) error {
	if err := publicSystemDirectory(filepath.Dir(target)); err != nil {
		return err
	}
	parent, err := os.OpenRoot(filepath.Dir(target))
	if err != nil {
		return err
	}
	defer parent.Close()
	if info, err := parent.Lstat(filepath.Base(target)); err == nil {
		owner, ok := info.Sys().(*syscall.Stat_t)
		if !ok || !info.Mode().IsRegular() || owner.Uid != 0 || info.Mode().Perm()&0022 != 0 {
			return errors.New("unsafe fixed support executable")
		}
		for _, entry := range bundle.Manifest.Files {
			if entry.Name == name && verifyFile(filepath.Dir(target), entry) == nil {
				if owner.Gid == 0 && info.Mode().Perm() == 0755 {
					return nil
				}
				file, err := parent.OpenFile(filepath.Base(target), os.O_RDONLY|syscall.O_NOFOLLOW, 0)
				if err != nil {
					return err
				}
				return errors.Join(file.Chown(0, 0), file.Chmod(0755), file.Sync(), file.Close())
			}
		}
	} else if !errors.Is(err, os.ErrNotExist) {
		return err
	}
	source, err := os.OpenRoot(bundle.Directory)
	if err != nil {
		return err
	}
	defer source.Close()
	staging := ".support-" + strconv.FormatInt(time.Now().UnixNano(), 16)
	if err = parent.Mkdir(staging, 0700); err != nil {
		return err
	}
	defer parent.Remove(staging)
	temp, err := parent.OpenRoot(staging)
	if err != nil {
		return err
	}
	defer temp.Close()
	defer temp.Remove(name)
	for _, entry := range bundle.Manifest.Files {
		if entry.Name != name {
			continue
		}
		if err = copyPayload(source, temp, entry); err != nil {
			return err
		}
		file, err := temp.OpenFile(name, os.O_RDONLY|syscall.O_NOFOLLOW, 0)
		if err != nil {
			return err
		}
		err = errors.Join(file.Chown(0, 0), file.Chmod(0755), file.Sync(), file.Close())
		if err != nil {
			return err
		}
		if err = parent.Rename(filepath.Join(staging, name), filepath.Base(target)); err != nil {
			return err
		}
		return syncDir(parent)
	}
	return errors.New("support executable absent from signed manifest")
}

func stageExtensionSupport(bundle *Bundle, o ExtensionOptions, plan *ExtensionPlan, verified releaseauth.Verified) error {
	if err := privateOwnedDir(o.RootPrefix, os.Geteuid(), os.Getegid()); err != nil {
		return err
	}
	root, err := os.OpenRoot(o.RootPrefix)
	if err != nil {
		return err
	}
	defer root.Close()
	for _, dir := range []string{"usr/lib/shikigami", "etc/systemd/system", "etc/sudoers.d", "var/lib/shikigami-region", "var/lib/shikigami-install"} {
		if err = root.MkdirAll(dir, 0700); err != nil {
			return err
		}
	}
	source, err := os.OpenRoot(bundle.Directory)
	if err != nil {
		return err
	}
	defer source.Close()
	binaries, err := root.OpenRoot("usr/lib/shikigami")
	if err != nil {
		return err
	}
	defer binaries.Close()
	for _, entry := range bundle.Manifest.Files {
		if (o.includes("region") && entry.Name == "shiki-region-helper") || (o.includes("browser") && entry.Name == "shiki-browser-runtime") {
			if err = copyPayload(source, binaries, entry); err != nil {
				return err
			}
		}
	}
	policy, _ := json.Marshal(map[string]int{"daemon_uid": plan.UID, "plan_ttl_seconds": 300, "dns_confirm_seconds": 120})
	files := map[string][]byte{"var/lib/shikigami-install/STAGED-NOT-ACTIVE": []byte("Inert fixture only. No root authorization, APT, services or host configuration was applied. Production helper paths remain fixed.\n")}
	if o.includes("region") {
		files["etc/shikigami-region-helper.json"] = append(policy, '\n')
		files["etc/sudoers.d/shikigami-region-"+strconv.Itoa(plan.UID)] = []byte(regionSudoers(plan.UID))
		files["etc/systemd/system/"+RegionGuardUnit] = []byte(regionGuardService())
		if err = root.MkdirAll(filepath.Dir(strings.TrimPrefix(regionDaemonDropIn, "/")), 0700); err != nil {
			return err
		}
		files[strings.TrimPrefix(regionDaemonDropIn, "/")] = regionDaemonServicePolicy(plan.UID)
	}
	if o.includes("browser") {
		const policy = "etc/opt/chrome/policies/managed/shikigami-browser.json"
		if err = root.MkdirAll(filepath.Dir(policy), 0700); err != nil {
			return err
		}
		files[policy] = chromeManagedPolicy()
	}
	receipt, _ := json.MarshalIndent(struct {
		Plan    *ExtensionPlan       `json:"plan"`
		Release releaseauth.Verified `json:"signed_release"`
	}{plan, verified}, "", "  ")
	files["var/lib/shikigami-install/extensions.json"] = append(receipt, '\n')
	for path, data := range files {
		if err = atomicExtensionFile(root, path, data, 0600); err != nil {
			return err
		}
	}
	if o.includes("browser") {
		if err = stageRuntimeInstallLock(root); err != nil {
			return err
		}
	}
	if o.BootUnlock {
		if err = stageBootUnlockTemplates(root, plan, o); err != nil {
			return err
		}
	}
	return syncDir(root)
}

func ensureExtensionLocales() error {
	data, err := readRegular("/etc", "locale.gen", 1<<20)
	if err != nil {
		return err
	}
	for _, locale := range []string{"en_US.UTF-8 UTF-8", "ja_JP.UTF-8 UTF-8", "zh_CN.UTF-8 UTF-8"} {
		found := false
		for _, line := range strings.Split(string(data), "\n") {
			if strings.TrimSpace(line) == locale {
				found = true
				break
			}
		}
		if !found {
			data = append(data, []byte("\n"+locale+"\n")...)
		}
	}
	return writeRootFile("/etc/locale.gen", data, 0644, false)
}


func lockExtensionInstallation() (func(), error) {
	if err := systemBinDirectory(filepath.Dir(extensionReceiptPath)); err != nil {
		return nil, err
	}
	file, err := os.OpenFile(filepath.Join(filepath.Dir(extensionReceiptPath), "extensions.lock"), os.O_CREATE|os.O_RDWR|syscall.O_NOFOLLOW|syscall.O_NONBLOCK, 0600)
	if err != nil {
		return nil, err
	}
	info, err := file.Stat()
	if err == nil {
		owner, ok := info.Sys().(*syscall.Stat_t)
		if !ok || owner.Uid != 0 || !info.Mode().IsRegular() || info.Mode().Perm() != 0600 {
			err = errors.New("unsafe extension installation lock")
		}
	}
	if err == nil {
		err = syscall.Flock(int(file.Fd()), syscall.LOCK_EX|syscall.LOCK_NB)
	}
	if err != nil {
		file.Close()
		return nil, fmt.Errorf("exclusive extension installation lock unavailable: %w", err)
	}
	return func() { _ = file.Close() }, nil
}

func trustedInstalledFile(path string, mode os.FileMode) error {
	info, err := os.Lstat(path)
	if err != nil {
		return err
	}
	owner, ok := info.Sys().(*syscall.Stat_t)
	if !ok || !info.Mode().IsRegular() || owner.Uid != 0 || info.Mode().Perm() != mode {
		return fmt.Errorf("unsafe installed root file %s", path)
	}
	for parent := filepath.Dir(path); ; parent = filepath.Dir(parent) {
		info, err = os.Lstat(parent)
		if err != nil {
			return err
		}
		owner, ok = info.Sys().(*syscall.Stat_t)
		if !ok || !info.IsDir() || owner.Uid != 0 || info.Mode().Perm()&0022 != 0 {
			return fmt.Errorf("unsafe root ancestor for %s", path)
		}
		if parent == "/" {
			return nil
		}
	}
}

func readExtensionReceipt() (*extensionReceipt, error) {
	if err := trustedInstalledFile(extensionReceiptPath, 0600); err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return nil, nil
		}
		return nil, err
	}
	data, err := readRegular(filepath.Dir(extensionReceiptPath), filepath.Base(extensionReceiptPath), 1<<20)
	if err != nil {
		return nil, err
	}
	var receipt extensionReceipt
	if err = decode(data, &receipt); err != nil {
		return nil, err
	}
	if receipt.Generated != "Generated by shiki-install" {
		return nil, errors.New("unrecognized installed support trust receipt")
	}
	return &receipt, nil
}

func recordExtensionReceipt(plan *ExtensionPlan, bundle *Bundle, verified releaseauth.Verified, o ExtensionOptions) error {
	receipt, err := readExtensionReceipt()
	if err != nil {
		return err
	}
	if receipt == nil {
		receipt = &extensionReceipt{Generated: "Generated by shiki-install"}
	}
	if receipt.SupportFiles == nil {
		receipt.SupportFiles = map[string]File{}
	}
	if receipt.SignedReleases == nil {
		receipt.SignedReleases = map[string]releaseauth.Verified{}
	}
	if bundle != nil {
		for _, entry := range bundle.Manifest.Files {
			if (o.includes("region") && entry.Name == "shiki-region-helper") || (o.includes("browser") && entry.Name == "shiki-browser-runtime") {
				receipt.SupportFiles[entry.Name] = entry
				receipt.SignedReleases[entry.Name] = verified
			}
		}
	}
	receipt.Plan, receipt.AppliedAt = plan, time.Now().UTC().Format(time.RFC3339)
	return saveExtensionReceipt(receipt)
}

func saveExtensionReceipt(receipt *extensionReceipt) error {
	data, err := json.MarshalIndent(receipt, "", "  ")
	if err != nil {
		return err
	}
	return writeRootFile(extensionReceiptPath, append(data, '\n'), 0600, true)
}

func verifyInstalledSupport(path string, receipt *extensionReceipt) error {
	if err := trustedInstalledFile(path, 0755); err != nil {
		return err
	}
	if receipt == nil {
		return errors.New("installed support has no protected signed-payload trust receipt; refusing root execution/removal")
	}
	name := filepath.Base(path)
	entry, exists := receipt.SupportFiles[name]
	release := receipt.SignedReleases[name]
	if !exists || entry.Name != name || !entry.Executable || release.ChecksumsSHA256 == "" || release.KeyFingerprintSHA256 == "" || release.Version == "" {
		return errors.New("installed support lacks signed payload provenance")
	}
	return verifyFile(filepath.Dir(path), entry)
}

type regionInstallStatus struct {
	State              string
	PendingOperationID string
}

// Only fixed root-owned, signed-receipted installed code is ever invoked here.
// Administrative helper actions are never in sudoers and never inherit SUDO_UID.
func callInstalledRegionHelper(ctx context.Context, action string) (regionInstallStatus, error) {
	var status regionInstallStatus
	if action != "activate" && action != "prepare-uninstall" {
		return status, errors.New("invalid installer helper action")
	}
	ctx, cancel := context.WithTimeout(ctx, 100*time.Second)
	defer cancel()
	cmd := exec.CommandContext(ctx, RegionHelperPath, action)
	cmd.Dir = "/"
	cmd.Env = []string{"PATH=/usr/sbin:/usr/bin:/sbin:/bin", "HOME=/root", "LANG=C.UTF-8"}
	cmd.WaitDelay = time.Second
	cmd.Stdin = strings.NewReader("{}\n")
	captured := &cappedOutput{limit: 64 << 10}
	cmd.Stdout, cmd.Stderr = captured, io.Discard
	if err := cmd.Run(); err != nil {
		return status, fmt.Errorf("installed region %s failed: %w; recovery components preserved", action, err)
	}
	data, truncated := captured.Bytes()
	if truncated {
		return status, errors.New("region helper status exceeds 64 KiB; recovery components preserved")
	}
	var response map[string]json.RawMessage
	if err := decode(data, &response); err != nil {
		return status, err
	}
	if value, exists := response["error"]; exists {
		var message string
		if err := json.Unmarshal(value, &message); err != nil {
			return status, err
		}
		if message != "" {
			return status, fmt.Errorf("region helper refused administrative action: %s", message)
		}
	}
	var rawStatus map[string]json.RawMessage
	if err := decode(response["status"], &rawStatus); err != nil {
		return status, errors.New("missing or invalid region status; recovery components preserved")
	}
	if err := json.Unmarshal(rawStatus["state"], &status.State); err != nil || status.State == "" {
		return status, errors.New("missing region recovery state")
	}
	if pending, exists := rawStatus["pending_operation_id"]; exists {
		if err := json.Unmarshal(pending, &status.PendingOperationID); err != nil {
			return status, err
		}
	}
	return status, nil
}

func (n *Native) removeRegionSupport(ctx context.Context, plan Plan, uid int) error {
	_, err := os.Lstat(RegionHelperPath)
	if errors.Is(err, os.ErrNotExist) {
		for _, path := range []string{RegionPolicyPath, "/etc/systemd/system/" + RegionGuardUnit} {
			if _, err := os.Lstat(path); !errors.Is(err, os.ErrNotExist) {
				return errors.New("region recovery components are incomplete; refusing to remove them without trusted helper status")
			}
		}
		return nil
	}
	if err != nil {
		return err
	}
	if err = checkRegionInstallationUID(ExtensionOptions{Component: "region"}, uid); err != nil {
		return err
	}
	receipt, err := readExtensionReceipt()
	if err != nil {
		return err
	}
	if err = verifyInstalledSupport(RegionHelperPath, receipt); err != nil {
		return err
	}
	status, err := callInstalledRegionHelper(ctx, "prepare-uninstall")
	if err != nil {
		return err
	}
	if err = regionUninstallReady(status); err != nil {
		return err
	}
	unit := "/etc/systemd/system/" + RegionGuardUnit
	data, exists, err := readManagedFile(unit)
	if err != nil {
		return err
	}
	if !exists {
		return errors.New("region guard unit is missing; cannot prove that a loaded guard has stopped; recovery components preserved")
	}
	if err = trustedInstalledFile(unit, 0644); err != nil {
		return err
	}
	if !bytes.Contains(data, []byte("\nExecStart="+RegionHelperPath+" guard\n")) {
		return errors.New("unrecognized region guard unit; recovery components preserved")
	}
	if err = run(ctx, plan, false, "/usr/bin/systemctl", "disable", "--now", RegionGuardUnit); err != nil {
		return err
	}
	if err = os.Remove(unit); err != nil {
		return err
	}
	if err = run(ctx, plan, false, "/usr/bin/systemctl", "daemon-reload"); err != nil {
		return err
	}
	if err = os.Remove(RegionHelperPath); err != nil {
		return err
	}
	if err = os.Remove(RegionPolicyPath); err != nil {
		return err
	}
	// Root journal, rollback snapshots and provenance remain intact. The durable
	// helper quiesce prevents late authorized invocations from starting changes.
	return nil
}

func removeBrowserSupport(ctx context.Context, plan Plan) error {
	_, binaryErr := os.Lstat(BrowserRuntimePath)
	_, lockErr := os.Lstat(BrowserRuntimeInstallLock)
	if errors.Is(binaryErr, os.ErrNotExist) && errors.Is(lockErr, os.ErrNotExist) {
		return nil
	}
	if binaryErr != nil && !errors.Is(binaryErr, os.ErrNotExist) {
		return binaryErr
	}
	unlock, err := lockBrowserRuntimeInstallation()
	if err != nil {
		return err
	}
	defer unlock()
	if busy, err := installedBrowserUnits(ctx, plan, false); err != nil {
		return err
	} else if busy {
		return errors.New("managed browser is still active; runtime removal refused")
	}
	if busy, err := pendingBrowserUnitJobs(ctx, plan); err != nil {
		return err
	} else if busy {
		return errors.New("managed browser start/stop jobs are still pending; runtime removal refused")
	}
	if errors.Is(binaryErr, os.ErrNotExist) {
		return nil
	}
	receipt, err := readExtensionReceipt()
	if err != nil {
		return err
	}
	if err = verifyInstalledSupport(BrowserRuntimePath, receipt); err != nil {
		return err
	}
	// The permanent non-executable lock inode remains for future installations.
	return os.Remove(BrowserRuntimePath)
}

func revokeRegionGrant(uid int) error {
	path := "/etc/sudoers.d/shikigami-region-" + strconv.Itoa(uid)
	if _, exists, err := readManagedFile(path); err != nil {
		return err
	} else if exists {
		if err = os.Remove(path); err != nil {
			return err
		}
		root, err := os.OpenRoot(filepath.Dir(path))
		if err != nil {
			return err
		}
		defer root.Close()
		return syncDir(root)
	}
	return nil
}

func regionUninstallReady(status regionInstallStatus) error {
	if status.State != "disabled" || status.PendingOperationID != "" {
		return fmt.Errorf("region recovery is not safely quiesced (state=%s pending=%s); guard, helper, policy and evidence preserved; uninstall incomplete", status.State, status.PendingOperationID)
	}
	return nil
}

func chromeInitialDefaults() []byte {
	return []byte("# Generated by shiki-install. Keep a fresh Chrome repository source-scoped and administrator-managed.\nrepo_add_once=\"false\"\nrepo_reenable_on_distupgrade=\"false\"\n")
}

func configureChromeDefaults() error {
	info, err := os.Lstat(chromeDefaultsPath)
	if errors.Is(err, os.ErrNotExist) {
		return writeRootFile(chromeDefaultsPath, chromeInitialDefaults(), 0644, false)
	}
	if err != nil {
		return err
	}
	if info.Mode().Perm()&0022 != 0 {
		return errors.New("existing Chrome package defaults are writable by other users")
	}
	// Preserve every existing package/update policy, including repository
	// reenabling behavior. The explicit source-scoped download remains separate.
	return trustedInstalledFile(chromeDefaultsPath, info.Mode().Perm())
}

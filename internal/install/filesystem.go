func privateOwnedDir(path string, uid, gid int) error {
	if !filepath.IsAbs(path) || filepath.Clean(path) == "/" {
		return errors.New("private directory must have an absolute non-root path")
	}
	fd, err := unix.Open("/", unix.O_RDONLY|unix.O_DIRECTORY|unix.O_CLOEXEC, 0)
	if err != nil {
		return err
	}
	defer func() { unix.Close(fd) }()
	parts := strings.Split(strings.TrimPrefix(filepath.Clean(path), "/"), "/")
	for index, part := range parts {
		created := false
		next, e := unix.Openat(fd, part, unix.O_RDONLY|unix.O_DIRECTORY|unix.O_NOFOLLOW|unix.O_CLOEXEC, 0)
		if errors.Is(e, unix.ENOENT) {
			if e = unix.Mkdirat(fd, part, 0700); e != nil && !errors.Is(e, unix.EEXIST) {
				return e
			}
			next, e = unix.Openat(fd, part, unix.O_RDONLY|unix.O_DIRECTORY|unix.O_NOFOLLOW|unix.O_CLOEXEC, 0)
			created = true
		}
		if e != nil {
			return e
		}
		unix.Close(fd)
		fd = next
		var stat unix.Stat_t
		if e = unix.Fstat(fd, &stat); e != nil {
			return e
		}
		if created {
			if e = unix.Fchown(fd, uid, gid); e != nil {
				return e
			}
		} else if index == len(parts)-1 && (stat.Uid != uint32(uid) || stat.Mode&0777 != 0700) {
			return errors.New("existing private directory has unexpected owner or permissions")
		}
	}
	return nil
}
func writeManagedFile(path string, data []byte, mode os.FileMode) error {
	if _, _, err := readManagedFile(path); err != nil {
		return err
	}
	parent, err := os.OpenRoot(filepath.Dir(path))
	if err != nil {
		return err
	}
	defer parent.Close()
	temp := "." + filepath.Base(path) + ".install-" + rand.Text()
	file, err := parent.OpenFile(temp, os.O_WRONLY|os.O_CREATE|os.O_EXCL|syscall.O_NOFOLLOW, mode)
	if err != nil {
		return err
	}
	defer parent.Remove(temp)
	_, err = file.Write(data)
	if err == nil {
		err = file.Sync()
	}
	closeErr := file.Close()
	if err != nil {
		return err
	}
	if closeErr != nil {
		return closeErr
	}
	if err = parent.Rename(temp, filepath.Base(path)); err != nil {
		return err
	}
	return syncDir(parent)
}

func systemBinDirectory(path string) error {
	if !filepath.IsAbs(path) {
		return errors.New("system binary directory must be absolute")
	}
	if err := os.MkdirAll(path, 0755); err != nil {
		return err
	}
	for current := path; ; current = filepath.Dir(current) {
		info, err := os.Lstat(current)
		if err != nil {
			return err
		}
		owner, ok := info.Sys().(*syscall.Stat_t)
		if !ok || !info.IsDir() || owner.Uid != 0 || info.Mode().Perm()&0022 != 0 {
			return errors.New("system binary directory and its parents must be root-owned and not writable by other users")
		}
		if filepath.Dir(current) == current {
			break
		}
	}
	return nil
}

func ownedServiceDirectory(path string, uid int) error {
	if !filepath.IsAbs(path) {
		return errors.New("service directory must be absolute")
	}
	if err := os.MkdirAll(path, 0755); err != nil {
		return err
	}
	info, err := os.Lstat(path)
	if err != nil {
		return err
	}
	owner, ok := info.Sys().(*syscall.Stat_t)
	if !ok || !info.IsDir() || owner.Uid != uint32(uid) || info.Mode().Perm()&0022 != 0 {
		return errors.New("service directory must be owned by its user and not writable by other users")
	}
	return nil
}

func readManagedFile(path string) ([]byte, bool, error) {
	f, err := os.OpenFile(path, os.O_RDONLY|syscall.O_NOFOLLOW|syscall.O_NONBLOCK, 0)
	if errors.Is(err, os.ErrNotExist) {
		return nil, false, nil
	}
	if err != nil {
		return nil, false, err
	}
	defer f.Close()
	info, err := f.Stat()
	if err != nil {
		return nil, false, err
	}
	owner, ok := info.Sys().(*syscall.Stat_t)
	if !ok || owner.Uid != uint32(os.Geteuid()) || !info.Mode().IsRegular() || info.Size() > 64<<10 {
		return nil, false, errors.New("unsafe or oversized service file")
	}
	data, err := io.ReadAll(io.LimitReader(f, (64<<10)+1))
	if err != nil {
		return nil, false, err
	}
	if len(data) > 64<<10 || !bytes.Contains(data, []byte("Generated by shiki-install")) {
		return nil, false, errors.New("refusing to replace or remove an unmanaged service file")
	}
	return data, true, nil
}

// Open each ancestor without following links and check ownership before creating
// the next component. An ordinary user cannot replace a privileged prefix while
// later activation code adjusts executable permissions or installs command links.
func ensureSystemPrefix(path string) error {
	fd, err := unix.Open("/", unix.O_RDONLY|unix.O_DIRECTORY|unix.O_CLOEXEC, 0)
	if err != nil {
		return err
	}
	defer func() { unix.Close(fd) }()
	for _, part := range strings.Split(strings.TrimPrefix(filepath.Clean(path), "/"), "/") {
		next, e := unix.Openat(fd, part, unix.O_RDONLY|unix.O_DIRECTORY|unix.O_NOFOLLOW|unix.O_CLOEXEC, 0)
		if errors.Is(e, unix.ENOENT) {
			if e = unix.Mkdirat(fd, part, 0700); e != nil && !errors.Is(e, unix.EEXIST) {
				return e
			}
			next, e = unix.Openat(fd, part, unix.O_RDONLY|unix.O_DIRECTORY|unix.O_NOFOLLOW|unix.O_CLOEXEC, 0)
		}
		if e != nil {
			return e
		}
		unix.Close(fd)
		fd = next
		var stat unix.Stat_t
		if e = unix.Fstat(fd, &stat); e != nil {
			return e
		}
		if stat.Uid != 0 || (stat.Mode&0022 != 0 && stat.Mode&unix.S_ISVTX == 0) {
			return errors.New("system prefix ancestors must be root-owned and protected from replacement")
		}
	}
	return nil
}

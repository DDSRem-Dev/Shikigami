package install

import (
	"os"
	"path/filepath"
	"testing"
)

func TestManagedServiceWritePreservesInterruptedTemporaryObjects(t *testing.T) {
	for _, kind := range []string{"regular", "symlink", "directory"} {
		t.Run(kind, func(t *testing.T) {
			directory := t.TempDir()
			path := filepath.Join(directory, "shiki-agent.service")
			old := []byte("# Generated by shiki-install\nold service\n")
			if err := os.WriteFile(path, old, 0600); err != nil {
				t.Fatal(err)
			}
			stale := filepath.Join(directory, ".shiki-agent.service.install")
			retained := []byte("interrupted evidence; do not remove")
			var err error
			switch kind {
			case "regular":
				err = os.WriteFile(stale, retained, 0600)
			case "symlink":
				if err := os.WriteFile(filepath.Join(directory, "unrelated"), retained, 0600); err != nil {
					t.Fatal(err)
				}
				err = os.Symlink("unrelated", stale)
			case "directory":
				err = os.Mkdir(stale, 0700)
			}
			if err != nil {
				t.Fatal(err)
			}
			staleInfo, err := os.Lstat(stale)
			if err != nil {
				t.Fatal(err)
			}
			next := []byte("# Generated by shiki-install\nnew service\n")
			if err := writeManagedFile(path, next, 0600); err != nil {
				t.Fatalf("interrupted temporary object prevented a fresh service write: %v", err)
			}
			if got, err := os.ReadFile(path); err != nil || string(got) != string(next) {
				t.Errorf("new managed service not installed: %q %v", got, err)
			}
			if got, err := os.Lstat(stale); err != nil || !os.SameFile(got, staleInfo) {
				t.Fatalf("stale object was removed or replaced: %v", err)
			}
			if kind != "directory" {
				if got, err := os.ReadFile(stale); err != nil || string(got) != string(retained) {
					t.Errorf("stale or unrelated contents modified: %q %v", got, err)
				}
			}
			entries, err := os.ReadDir(directory)
			expected := 2
			if kind == "symlink" {
				expected++
			}
			if err != nil || len(entries) != expected {
				t.Errorf("new transaction leaked temporary entries: %v %v", entries, err)
			}
		})
	}
}

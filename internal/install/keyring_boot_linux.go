type bootUnlockReceipt struct {
	UID              int    `json:"uid"`
	Mode             string `json:"mode"`
	Enabled          bool   `json:"enabled"`
	CredentialSHA256 string `json:"credential_sha256,omitempty"`
	Provisioned      bool   `json:"provisioned,omitempty"`
}

type bootKeyringPolicy struct {
	SchemaVersion  int    `json:"schema_version"`
	UID            int    `json:"uid"`
	Mode           string `json:"mode"`
	AllowProvision bool   `json:"allow_provision"`
}

func keyringPolicyPath(uid int) string {
	return fmt.Sprintf("/etc/shikigami/browser-keyring-%d.json", uid)
}
func keyringCredentialPath(uid int) string {
	return fmt.Sprintf("/etc/shikigami/credentials/browser-keyring-%d.cred", uid)
}
func keyringEnrollmentCredentialPath(uid int) string {
	return fmt.Sprintf("/etc/shikigami/credentials/browser-keyring-%d.enroll.cred", uid)
}
func keyringUnit(uid int, enrollment bool) string {
	if enrollment {
		return fmt.Sprintf("shikigami-browser-keyring-provision-%d.service", uid)
	}
	return fmt.Sprintf("shikigami-browser-keyring-%d.service", uid)
}

func keyringStore(account *user.User, mode string) string {
	if mode == "dedicated" {
		return filepath.Join(account.HomeDir, ".local/share/shikigami/browser-keyring/keyrings/login.keyring")
	}
	return filepath.Join(account.HomeDir, ".local/share/keyrings/login.keyring")
}

func renderKeyringUnlockUnit(account *user.User, uid int, enrollment, provision bool) ([]byte, error) {
	gid, err := strconv.Atoi(account.Gid)
	if err != nil || gid < 0 {
		return nil, errors.New("invalid keyring service account group")
	}
	if !filepath.IsAbs(account.HomeDir) || filepath.Clean(account.HomeDir) == "/" {
		return nil, errors.New("keyring service requires an ordinary account home")
	}
	home, err := unitQuote("HOME=" + account.HomeDir)
	if err != nil {
		return nil, err
	}
	credential := keyringCredentialPath(uid)
	if enrollment {
		credential = keyringEnrollmentCredentialPath(uid)
	}
	action := "unlock-keyring"
	if provision {
		action = "provision-keyring"
	}
	text := fmt.Sprintf("# Generated by shiki-install. Secret bytes are supplied only by systemd encrypted credentials.\n[Unit]\nDescription=Shikigami encrypted browser keyring unlock for UID %d\nRequires=user@%d.service\nAfter=user@%d.service\nBefore=shiki-daemon.service\n[Service]\nType=oneshot\nRemainAfterExit=yes\nUser=%d\nGroup=%d\nEnvironment=%s\nEnvironment=XDG_RUNTIME_DIR=/run/user/%d\nEnvironment=DBUS_SESSION_BUS_ADDRESS=unix:path=/run/user/%d/bus\nLoadCredentialEncrypted=keyring-password:%s\nExecStart=%s %s\nUMask=0077\nLimitCORE=0\nNoNewPrivileges=true\nPrivateTmp=true\nProtectSystem=full\nKillMode=control-group\nTimeoutStartSec=120\nTimeoutStopSec=15\nRestart=no\nStandardOutput=null\nStandardError=null\n", uid, uid, uid, uid, gid, home, uid, uid, credential, BrowserRuntimePath, action)
	if !enrollment {
		text += "[Install]\nWantedBy=multi-user.target\n"
	}
	return []byte(text), nil
}

func readBootKeyringPolicy(uid int) (*bootKeyringPolicy, error) {
	path := keyringPolicyPath(uid)
	if err := trustedInstalledFile(path, 0644); err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return nil, nil
		}
		return nil, err
	}
	data, err := readRegular(filepath.Dir(path), filepath.Base(path), 64<<10)
	if err != nil {
		return nil, err
	}
	var policy bootKeyringPolicy
	if err = decode(data, &policy); err != nil {
		return nil, err
	}
	if policy.SchemaVersion != 1 || policy.UID != uid || (policy.Mode != "dedicated" && policy.Mode != "existing-login") {
		return nil, errors.New("incompatible user-specific boot keyring policy")
	}
	return &policy, nil
}

func appendBootUnlockPlan(ctx context.Context, plan *ExtensionPlan, o ExtensionOptions, account *user.User) error {
	if _, err := renderKeyringUnlockUnit(account, plan.UID, false, false); err != nil {
		return err
	}
	plan.BootUnlock, plan.KeyringMode, plan.ProvisionKeyring, plan.ReuseEncryptedCredential = true, o.KeyringMode, o.ProvisionKeyring, o.ReuseKeyringCredential
	plan.Paths = append(plan.Paths, keyringPolicyPath(plan.UID), keyringCredentialPath(plan.UID), keyringEnrollmentCredentialPath(plan.UID), "/etc/systemd/system/"+keyringUnit(plan.UID, false), "/etc/systemd/system/"+keyringUnit(plan.UID, true), keyringStore(account, o.KeyringMode), "/var/lib/systemd/credential.secret")
	plan.Sources = append(plan.Sources, "Local systemd-creds --with-key=host encryption and root-owned LoadCredentialEncrypted service; fixed signed runtime unlock-keyring/provision-keyring actions only. No TPM dependency or plaintext fallback.")
	plan.Warnings = append(plan.Warnings, "EXPLICIT UNATTENDED BOOT UNLOCK: host-key encryption protects the stored credential at rest, but a whole-disk copy together with /var/lib/systemd/credential.secret, or a root compromise, can decrypt it. This is not TPM-backed protection against root.", "Password is read only after --yes, from a hidden terminal or explicitly owned private stdin/file; never argv, environment, logs, ordinary backups, or a plaintext password file. systemd supplies a private RAM credential to the ordinary-UID helper.", "Enrollment requires stopped managed Chrome and no pending starts. The candidate encrypted password is verified against an isolated encrypted keyring copy before committing it; existing keyrings are never reset. A failed operation retains data and does not roll back installed packages.", "Dedicated mode uses a new private store/bus without touching existing user keyrings; creation additionally requires --provision-keyring and an absent dedicated store. Existing-login mode unlocks the user's existing encrypted login keyring and therefore all secrets in that collection, not only Chrome.", "Choose existing-login for previously created profiles using the user keyring. Dedicated mode is intended before creating profiles; there is no silent cookie-encryption-key migration. A previously configured mode is immutable.", "Uninstall stops/disables/removes these unlock services and root policy after managed Chrome stops, but preserves the encrypted credential, encrypted keyring and profiles for recovery. The global systemd host key is never removed.")
	if o.StageOnly {
		plan.Warnings = append(plan.Warnings, "Stage-only writes inert policy/unit templates only. It never reads a password, generates a host key, encrypts/decrypts a credential, starts a keyring, or writes a fake credential payload.")
		return nil
	}
	if info, err := os.Stat("/usr/bin/systemd-creds"); err != nil || !info.Mode().IsRegular() || info.Mode().Perm()&0111 == 0 {
		plan.Blocked = append(plan.Blocked, "systemd-creds with host-key encrypted credential support is required")
	} else if version, err := extensionCommand(ctx, "", "/usr/bin/systemd-creds", "--version"); err == nil {
		plan.InstalledVersions["systemd-creds"] = strings.TrimSpace(string(version))
	} else {
		plan.Blocked = append(plan.Blocked, "systemd-creds version could not be inspected")
	}
	if info, err := os.Lstat(account.HomeDir); err != nil || !info.IsDir() {
		plan.Blocked = append(plan.Blocked, "keyring account home must exist as a non-symlink ordinary-user directory")
	} else if owner, ok := info.Sys().(*syscall.Stat_t); !ok || owner.Uid != uint32(plan.UID) || info.Mode().Perm()&0022 != 0 {
		plan.Blocked = append(plan.Blocked, "keyring account home ownership/permissions are unsafe")
	}
	if info, err := os.Lstat("/etc/shikigami"); err == nil {
		owner, ok := info.Sys().(*syscall.Stat_t)
		if !ok || owner.Uid != 0 || !info.IsDir() || info.Mode().Perm()&0022 != 0 {
			plan.Blocked = append(plan.Blocked, "/etc/shikigami must be a protected root-owned policy directory; unsafe directory is preserved for administrator review")
		} else if info.Mode().Perm() != 0755 {
			plan.Warnings = append(plan.Warnings, "Approved setup repairs /etc/shikigami to public directory mode 0755 so the ordinary runtime can read its non-secret policy; credential subdirectories and files remain private.")
		}
	} else if !errors.Is(err, os.ErrNotExist) {
		plan.Blocked = append(plan.Blocked, "cannot inspect root browser policy directory")
	}
	policy, err := readBootKeyringPolicy(plan.UID)
	if err != nil {
		plan.Blocked = append(plan.Blocked, err.Error())
	}
	receipt, receiptErr := readExtensionReceipt()
	if receiptErr != nil {
		plan.Blocked = append(plan.Blocked, receiptErr.Error())
	}
	if err := checkBootUnlockNamespace(receipt, plan.UID); err != nil {
		plan.Blocked = append(plan.Blocked, err.Error())
	}
	if policy != nil && policy.Mode != o.KeyringMode {
		plan.Blocked = append(plan.Blocked, "changing existing keyring mode would change retained profile encryption context; existing policy is preserved")
	}
	if receipt != nil && receipt.BootUnlock != nil {
		if receipt.BootUnlock.UID != plan.UID || receipt.BootUnlock.Mode != o.KeyringMode {
			plan.Blocked = append(plan.Blocked, "enrolled credential belongs to a different UID or keyring mode")
		}
	} else if policy != nil {
		plan.Blocked = append(plan.Blocked, "existing boot keyring policy is not owned by this installer's receipt")
	}
	if o.ReuseKeyringCredential && (receipt == nil || receipt.BootUnlock == nil || receipt.BootUnlock.CredentialSHA256 == "") {
		plan.Blocked = append(plan.Blocked, "no protected enrolled encrypted credential is available for explicit reuse")
	}
	if !o.ReuseKeyringCredential && o.ReadKeyringSecret == nil {
		plan.Blocked = append(plan.Blocked, "explicit boot unlock enrollment needs hidden terminal or private secret stdin/file input")
	}
	plan.Commands = append(plan.Commands, ExtensionCommand{Program: "/usr/bin/loginctl", Args: []string{"enable-linger", strconv.Itoa(plan.UID)}}, ExtensionCommand{Program: "/usr/bin/systemctl", Args: []string{"start", fmt.Sprintf("user@%d.service", plan.UID)}})
	if !o.ReuseKeyringCredential {
		plan.Commands = append(plan.Commands, ExtensionCommand{Program: "/usr/bin/systemd-creds", Args: []string{"setup"}}, ExtensionCommand{Program: "/usr/bin/systemd-creds", Args: []string{"encrypt", "--with-key=host", "--name=keyring-password", "-", "<root-private-encrypted-candidate>"}})
	}
	plan.Commands = append(plan.Commands, ExtensionCommand{Program: "/usr/bin/systemctl", Args: []string{"daemon-reload"}}, ExtensionCommand{Program: "/usr/bin/systemctl", Args: []string{"restart", keyringUnit(plan.UID, true)}}, ExtensionCommand{Program: "/usr/bin/systemctl", Args: []string{"stop", keyringUnit(plan.UID, true)}}, ExtensionCommand{Program: "/usr/bin/systemctl", Args: []string{"enable", keyringUnit(plan.UID, false)}}, ExtensionCommand{Program: "/usr/bin/systemctl", Args: []string{"restart", keyringUnit(plan.UID, false)}})
	return nil
}

func lockRootCredentialCoreDumps(o ExtensionOptions) error {
	if !o.BootUnlock || o.StageOnly {
		return nil
	}
	if err := syscall.Setrlimit(syscall.RLIMIT_CORE, &syscall.Rlimit{Cur: 0, Max: 0}); err != nil {
		return errors.New("cannot disable installer core dumps before reading a credential")
	}
	return nil
}

func writeBootKeyringPolicy(uid int, mode string, provision bool) error {
	data, err := json.Marshal(bootKeyringPolicy{SchemaVersion: 1, UID: uid, Mode: mode, AllowProvision: provision})
	if err != nil {
		return err
	}
	return writeRootFile(keyringPolicyPath(uid), append(data, '\n'), 0644, false)
}

func encryptKeyringPassword(ctx context.Context, o ExtensionOptions, work string) ([]byte, error) {
	secret, err := o.ReadKeyringSecret(ctx)
	if err != nil {
		return nil, err
	}
	defer func() {
		if secret != nil {
			clear(secret[:cap(secret)])
		}
	}()
	if len(secret) < 1 || len(secret) > 4096 || bytes.IndexAny(secret, "\x00\r\n") >= 0 || !utf8.Valid(secret) {
		return nil, errors.New("invalid bounded keyring password input")
	}
	if err = extensionRun(ctx, "", "/usr/bin/systemd-creds", "setup"); err != nil {
		return nil, err
	}
	ctx, cancel := context.WithTimeout(ctx, 60*time.Second)
	defer cancel()
	output := filepath.Join(work, "keyring-password.encrypted")
	cmd := exec.CommandContext(ctx, "/usr/bin/systemd-creds", "encrypt", "--with-key=host", "--name=keyring-password", "-", output)
	cmd.Dir = "/"
	cmd.Env = []string{"PATH=/usr/sbin:/usr/bin:/sbin:/bin", "HOME=/root", "LANG=C.UTF-8", "SYSTEMD_LOG_LEVEL=err"}
	cmd.Stdin = bytes.NewReader(secret)
	cmd.Stdout, cmd.Stderr = io.Discard, io.Discard
	cmd.WaitDelay = time.Second
	if err = cmd.Run(); err != nil {
		return nil, fmt.Errorf("systemd host-key credential encryption failed (secret output suppressed): %w", err)
	}
	data, err := readRegular(work, filepath.Base(output), 64<<10)
	if err != nil || len(data) == 0 {
		return nil, errors.New("systemd did not create a bounded encrypted credential")
	}
	return data, nil
}

func installBootUnlock(ctx context.Context, plan *ExtensionPlan, o ExtensionOptions, work string) (result error) {
	receipt, err := readExtensionReceipt()
	if err != nil {
		return err
	}
	if err = verifyInstalledSupport(BrowserRuntimePath, receipt); err != nil {
		return err
	}
	unlock, err := lockBrowserRuntimeInstallation()
	if err != nil {
		return err
	}
	defer unlock()
	account, err := user.Lookup(plan.User)
	if err != nil {
		return err
	}
	ordinary := Plan{Role: "daemon", User: plan.User, Home: account.HomeDir, Path: "/usr/bin:/bin"}
	if busy, err := installedBrowserUnits(ctx, ordinary, false); err != nil {
		return err
	} else if busy {
		return errors.New("explicitly stop managed Chrome before credential enrollment")
	}
	if busy, err := pendingBrowserUnitJobs(ctx, ordinary); err != nil {
		return err
	} else if busy {
		return errors.New("credential enrollment refuses pending browser unit jobs")
	}
	policy, err := readBootKeyringPolicy(plan.UID)
	if err != nil {
		return err
	}
	if policy != nil && policy.Mode != o.KeyringMode {
		return errors.New("refusing to change retained profile keyring mode")
	}
	if receipt.BootUnlock != nil && (receipt.BootUnlock.UID != plan.UID || receipt.BootUnlock.Mode != o.KeyringMode) {
		return errors.New("enrolled keyring UID/mode differs from this explicit plan")
	}
	if err = checkBootUnlockNamespace(receipt, plan.UID); err != nil {
		return err
	}
	if err = extensionRun(ctx, "", "/usr/bin/loginctl", "enable-linger", strconv.Itoa(plan.UID)); err != nil {
		return err
	}
	if err = extensionRun(ctx, "", "/usr/bin/systemctl", "start", fmt.Sprintf("user@%d.service", plan.UID)); err != nil {
		return err
	}
	var encrypted []byte
	if o.ReuseKeyringCredential {
		if receipt.BootUnlock == nil || receipt.BootUnlock.CredentialSHA256 == "" {
			return errors.New("no installed encrypted credential provenance is available")
		}
		if err = trustedInstalledFile(keyringCredentialPath(plan.UID), 0600); err != nil {
			return err
		}
		encrypted, err = readRegular(filepath.Dir(keyringCredentialPath(plan.UID)), filepath.Base(keyringCredentialPath(plan.UID)), 64<<10)
		if err != nil {
			return err
		}
		if digest(encrypted) != receipt.BootUnlock.CredentialSHA256 {
			return errors.New("encrypted credential differs from its protected enrollment receipt")
		}
	} else {
		if o.ReadKeyringSecret == nil {
			return errors.New("missing explicit keyring secret input")
		}
		encrypted, err = encryptKeyringPassword(ctx, o, work)
		if err != nil {
			return err
		}
	}
	if err = publicSystemDirectory("/etc/shikigami"); err != nil {
		return err
	}
	if err = ensureSystemPrefix("/etc/shikigami/credentials"); err != nil {
		return err
	}
	if err = privateOwnedDir("/etc/shikigami/credentials", 0, 0); err != nil {
		return err
	}
	if receipt.BootUnlock == nil {
		receipt.BootUnlock = &bootUnlockReceipt{UID: plan.UID, Mode: o.KeyringMode}
	}
	receipt.Plan = plan
	if err = saveExtensionReceipt(receipt); err != nil {
		return err
	}
	// A failed enrollment may preserve an encrypted store, but may never leave
	// ongoing permission to create/reset it. Normal boot unlock never creates.
	defer func() { result = errors.Join(result, writeBootKeyringPolicy(plan.UID, o.KeyringMode, false)) }()
	if err = writeBootKeyringPolicy(plan.UID, o.KeyringMode, o.ProvisionKeyring); err != nil {
		return err
	}
	candidate := keyringEnrollmentCredentialPath(plan.UID)
	if err = writeRootFile(candidate, encrypted, 0600, false); err != nil {
		return err
	}
	defer func() {
		err := os.Remove(candidate)
		if err != nil && !errors.Is(err, os.ErrNotExist) {
			result = errors.Join(result, err)
		}
	}()
	enrollment, err := renderKeyringUnlockUnit(account, plan.UID, true, o.ProvisionKeyring)
	if err != nil {
		return err
	}
	enrollmentPath := "/etc/systemd/system/" + keyringUnit(plan.UID, true)
	if err = writeRootFile(enrollmentPath, enrollment, 0644, true); err != nil {
		return err
	}
	enrollmentRemoved := false
	defer func() {
		if enrollmentRemoved {
			return
		}
		cleanupCtx, cancel := context.WithTimeout(context.WithoutCancel(ctx), 45*time.Second)
		defer cancel()
		stopErr := extensionRun(cleanupCtx, "", "/usr/bin/systemctl", "stop", keyringUnit(plan.UID, true))
		if stopErr == nil {
			stopErr = os.Remove(enrollmentPath)
			if errors.Is(stopErr, os.ErrNotExist) {
				stopErr = nil
			}
			if stopErr == nil {
				stopErr = extensionRun(cleanupCtx, "", "/usr/bin/systemctl", "daemon-reload")
			}
		}
		result = errors.Join(result, stopErr)
	}()
	if err = extensionRun(ctx, "", "/usr/bin/systemctl", "daemon-reload"); err != nil {
		return err
	}
	if err = extensionRun(ctx, "", "/usr/bin/systemctl", "restart", keyringUnit(plan.UID, true)); err != nil {
		return keyringEnrollmentFailure(ctx, plan.UID)
	}
	if err = writeRootFile(keyringCredentialPath(plan.UID), encrypted, 0600, false); err != nil {
		return err
	}
	receipt.BootUnlock.CredentialSHA256 = digest(encrypted)
	receipt.BootUnlock.Provisioned = receipt.BootUnlock.Provisioned || o.ProvisionKeyring
	if err = saveExtensionReceipt(receipt); err != nil {
		return err
	}
	if err = writeBootKeyringPolicy(plan.UID, o.KeyringMode, false); err != nil {
		return err
	}
	if err = extensionRun(ctx, "", "/usr/bin/systemctl", "stop", keyringUnit(plan.UID, true)); err != nil {
		return err
	}
	if err = os.Remove(enrollmentPath); err != nil {
		return err
	}
	enrollmentRemoved = true
	unit, err := renderKeyringUnlockUnit(account, plan.UID, false, false)
	if err != nil {
		return err
	}
	if err = writeRootFile("/etc/systemd/system/"+keyringUnit(plan.UID, false), unit, 0644, true); err != nil {
		return err
	}
	if err = extensionRun(ctx, "", "/usr/bin/systemctl", "daemon-reload"); err != nil {
		return err
	}
	if err = extensionRun(ctx, "", "/usr/bin/systemctl", "enable", keyringUnit(plan.UID, false)); err != nil {
		return err
	}
	if err = extensionRun(ctx, "", "/usr/bin/systemctl", "restart", keyringUnit(plan.UID, false)); err != nil {
		return errors.New("encrypted boot unlock service failed actual keyring verification; installed encrypted credential and keyrings are preserved")
	}
	receipt, err = readExtensionReceipt()
	if err != nil {
		return err
	}
	receipt.BootUnlock = &bootUnlockReceipt{UID: plan.UID, Mode: o.KeyringMode, Enabled: true, CredentialSHA256: digest(encrypted), Provisioned: o.ProvisionKeyring || receipt.BootUnlock.Provisioned}
	receipt.AppliedAt = time.Now().UTC().Format(time.RFC3339)
	return saveExtensionReceipt(receipt)
}

// Only systemd's fixed status fields are reported. The runtime and its children
// can handle secrets, so their output must never be copied into diagnostics.
func keyringEnrollmentFailure(parent context.Context, uid int) error {
	ctx, cancel := context.WithTimeout(context.WithoutCancel(parent), 5*time.Second)
	defer cancel()
	unit := keyringUnit(uid, true)
	cmd := exec.CommandContext(ctx, "/usr/bin/systemctl", "show", unit, "--property=Result,ExecMainCode,ExecMainStatus")
	cmd.Env = []string{"PATH=/usr/bin:/bin", "LANG=C.UTF-8"}
	cmd.WaitDelay = time.Second
	captured := &cappedOutput{limit: 4096}
	cmd.Stdout, cmd.Stderr = captured, io.Discard
	status := ""
	if cmd.Run() == nil {
		data, truncated := captured.Bytes()
		if !truncated {
			status = keyringServiceStatus(data)
		}
	}
	return fmt.Errorf("credential enrollment service %s failed%s; no candidate credential was committed and existing keyrings were not reset. Inspect: journalctl -b -u %s --no-pager -n 50", unit, status, unit)
}

func keyringServiceStatus(data []byte) string {
	var values []string
	for _, line := range strings.Split(string(data), "\n") {
		key, value, ok := strings.Cut(line, "=")
		if !ok || (key != "Result" && key != "ExecMainCode" && key != "ExecMainStatus") || len(value) == 0 || len(value) > 32 {
			continue
		}
		valid := true
		for _, char := range value {
			if (char < 'a' || char > 'z') && (char < '0' || char > '9') && char != '-' {
				valid = false
			}
		}
		if valid {
			values = append(values, key+"="+value)
		}
	}
	if len(values) == 0 {
		return ""
	}
	return " (" + strings.Join(values, ", ") + ")"
}

func removeBootUnlock(ctx context.Context, plan Plan, uid int) error {
	receipt, err := readExtensionReceipt()
	if err != nil || receipt == nil || receipt.BootUnlock == nil {
		return err
	}
	if receipt.BootUnlock.UID != uid {
		return errors.New("boot unlock service belongs to another UID; refusing cross-user cleanup")
	}
	for _, enrollment := range []bool{true, false} {
		path := "/etc/systemd/system/" + keyringUnit(uid, enrollment)
		data, exists, err := readManagedFile(path)
		if err != nil {
			return err
		}
		if !exists {
			absent, err := keyringUnitAbsent(ctx, keyringUnit(uid, enrollment))
			if err != nil {
				return err
			}
			if !absent {
				return errors.New("keyring unlock unit file is missing but a loaded unit remains; cleanup refused without a trusted service definition")
			}
			continue
		}
		if err = trustedInstalledFile(path, 0644); err != nil {
			return err
		}
		if !bytes.Contains(data, []byte("\nUser="+strconv.Itoa(uid)+"\n")) || !bytes.Contains(data, []byte("\nExecStart="+BrowserRuntimePath+" ")) {
			return errors.New("unrecognized keyring unlock unit; preserved for administrator review")
		}
		if err = run(ctx, plan, false, "/usr/bin/systemctl", "disable", "--now", keyringUnit(uid, enrollment)); err != nil {
			return err
		}
		if err = os.Remove(path); err != nil {
			return err
		}
	}
	if policy, err := readBootKeyringPolicy(uid); err != nil {
		return err
	} else if policy != nil {
		if policy.Mode != receipt.BootUnlock.Mode {
			return errors.New("keyring root policy changed; preserve it and report incomplete uninstall")
		}
		if err = os.Remove(keyringPolicyPath(uid)); err != nil {
			return err
		}
	}
	if err = run(ctx, plan, false, "/usr/bin/systemctl", "daemon-reload"); err != nil {
		return err
	}
	receipt.BootUnlock.Enabled = false
	// Keep only encrypted recovery material; no unlock service or authorization.
	return saveExtensionReceipt(receipt)
}

func stageBootUnlockTemplates(root *os.Root, plan *ExtensionPlan, o ExtensionOptions) error {
	account, err := user.Lookup(plan.User)
	if err != nil {
		return err
	}
	if err = root.MkdirAll("etc/shikigami/credentials", 0700); err != nil {
		return err
	}
	policy, err := json.Marshal(bootKeyringPolicy{SchemaVersion: 1, UID: plan.UID, Mode: o.KeyringMode, AllowProvision: o.ProvisionKeyring})
	if err != nil {
		return err
	}
	if err = atomicExtensionFile(root, strings.TrimPrefix(keyringPolicyPath(plan.UID), "/"), append(policy, '\n'), 0600); err != nil {
		return err
	}
	for _, enrollment := range []bool{true, false} {
		unit, err := renderKeyringUnlockUnit(account, plan.UID, enrollment, enrollment && o.ProvisionKeyring)
		if err != nil {
			return err
		}
		if err = atomicExtensionFile(root, "etc/systemd/system/"+keyringUnit(plan.UID, enrollment), unit, 0600); err != nil {
			return err
		}
	}
	return nil
}

func keyringUnitAbsent(ctx context.Context, unit string) (bool, error) {
	ctx, cancel := context.WithTimeout(ctx, 15*time.Second)
	defer cancel()
	cmd := exec.CommandContext(ctx, "/usr/bin/systemctl", "show", unit, "--property=LoadState,ActiveState")
	cmd.Env = []string{"PATH=/usr/sbin:/usr/bin:/sbin:/bin", "HOME=/root", "LANG=C.UTF-8"}
	cmd.WaitDelay = time.Second
	captured := &cappedOutput{limit: 16 << 10}
	cmd.Stdout, cmd.Stderr = captured, io.Discard
	runErr := cmd.Run()
	data, cut := captured.Bytes()
	if cut {
		return false, errors.New("keyring unit absence status exceeds bounded output")
	}
	values := map[string]string{}
	for _, line := range strings.Split(string(data), "\n") {
		key, value, ok := strings.Cut(line, "=")
		if ok {
			values[key] = value
		}
	}
	if values["LoadState"] == "not-found" && (values["ActiveState"] == "inactive" || values["ActiveState"] == "failed") {
		return true, nil
	}
	if runErr != nil {
		return false, fmt.Errorf("cannot prove missing keyring unit is inactive: %w", runErr)
	}
	if values["LoadState"] == "" || values["ActiveState"] == "" {
		return false, errors.New("missing keyring unit load/active evidence")
	}
	return false, nil
}

func checkBootUnlockNamespace(receipt *extensionReceipt, uid int) error {
	if receipt == nil || receipt.BootUnlock == nil {
		for _, path := range []string{keyringPolicyPath(uid), keyringCredentialPath(uid), keyringEnrollmentCredentialPath(uid), "/etc/systemd/system/" + keyringUnit(uid, false), "/etc/systemd/system/" + keyringUnit(uid, true)} {
			if _, err := os.Lstat(path); err == nil {
				return errors.New("unmanaged boot keyring policy, credential or unit exists; preserve it for explicit administrator review")
			} else if !errors.Is(err, os.ErrNotExist) {
				return err
			}
		}
		return nil
	}
	if receipt.BootUnlock.UID != uid {
		return errors.New("boot keyring namespace belongs to a different UID")
	}
	if _, err := os.Lstat(keyringCredentialPath(uid)); err == nil && receipt.BootUnlock.CredentialSHA256 != "" {
		if err := trustedInstalledFile(keyringCredentialPath(uid), 0600); err != nil {
			return err
		}
		data, err := readRegular(filepath.Dir(keyringCredentialPath(uid)), filepath.Base(keyringCredentialPath(uid)), 64<<10)
		if err != nil {
			return err
		}
		if digest(data) != receipt.BootUnlock.CredentialSHA256 {
			return errors.New("existing encrypted credential was changed outside its protected enrollment receipt")
		}
	} else if err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	return nil
}

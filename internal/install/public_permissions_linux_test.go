func TestPublicInstallationDirectoriesUnderPrivateUmask(t *testing.T) {
	if os.Geteuid() != 0 {
		t.Skip("requires isolated Linux root and a separate ordinary UID")
	}
	if os.Getenv("SHIKI_PRIVATE_UMASK_TEST") != "1" {
		cmd := exec.Command(os.Args[0], "-test.run=^TestPublicInstallationDirectoriesUnderPrivateUmask$", "-test.v")
		cmd.Env = append(os.Environ(), "SHIKI_PRIVATE_UMASK_TEST=1")
		if output, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("private umask subprocess: %v\n%s", err, output)
		}
		return
	}
	previous := syscall.Umask(0077)
	defer syscall.Umask(previous)
	root, err := os.MkdirTemp("/var/lib", "shiki-public-permissions-test-")
	if err != nil {
		t.Fatal(err)
	}
	defer os.RemoveAll(root)
	if err := publicSystemDirectory(root); err != nil {
		t.Fatal(err)
	}
	payload := []byte("#!/bin/sh\nprintf 'ordinary-runtime-ok\\n'\n")
	source := filepath.Join(root, "source")
	if err := os.Mkdir(source, 0700); err != nil {
		t.Fatal(err)
	}
	name := "shiki-browser-runtime"
	if err := os.WriteFile(filepath.Join(source, name), payload, 0600); err != nil {
		t.Fatal(err)
	}
	bundle := &Bundle{Directory: source, Manifest: Manifest{Files: []File{{Name: name, SHA256: digest(payload), Size: int64(len(payload)), Executable: true}}}}
	binary := filepath.Join(root, "usr", "lib", "shikigami", name)
	if err := copyExtensionBinary(bundle, name, binary); err != nil {
		t.Fatal(err)
	}
	ordinaryRun := func(program string, args ...string) (string, error) {
		cmd := exec.Command(program, args...)
		cmd.SysProcAttr = &syscall.SysProcAttr{Credential: &syscall.Credential{Uid: 65534, Gid: 65534}}
		output, err := cmd.CombinedOutput()
		return string(output), err
	}
	if output, err := ordinaryRun(binary); err != nil || output != "ordinary-runtime-ok\n" {
		t.Fatalf("fresh executable unavailable under umask 077: %v %q", err, output)
	}
	// Reproduce alpha.4's already-created inaccessible directory, then repair
	// without replacing the authenticated executable or opening secret children.
	before, err := os.Stat(binary)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.Chmod(filepath.Dir(binary), 0700); err != nil {
		t.Fatal(err)
	}
	if _, err := ordinaryRun(binary); err == nil {
		t.Fatal("fixture did not reproduce EXEC permission denial")
	}
	if err := copyExtensionBinary(bundle, name, binary); err != nil {
		t.Fatal(err)
	}
	after, err := os.Stat(binary)
	if err != nil || !os.SameFile(before, after) {
		t.Fatal("repair replaced identical runtime inode", err)
	}
	if output, err := ordinaryRun(binary); err != nil || output != "ordinary-runtime-ok\n" {
		t.Fatalf("repaired executable unavailable: %v %q", err, output)
	}
	policyDir := filepath.Join(root, "etc", "shikigami")
	if err := ensureSystemPrefix(policyDir); err != nil {
		t.Fatal(err)
	}
	// The system /etc ancestor is normally public. Reproduce only the owned
	// application directory's old 0700 mode, not an administrator-private /etc.
	if err := os.Chmod(filepath.Dir(policyDir), 0755); err != nil {
		t.Fatal(err)
	}
	credentials := filepath.Join(policyDir, "credentials")
	if err := privateOwnedDir(credentials, 0, 0); err != nil {
		t.Fatal(err)
	}
	secret := filepath.Join(credentials, "test.cred")
	if err := writeRootFile(secret, []byte("private-credential-fixture"), 0600, false); err != nil {
		t.Fatal(err)
	}
	policy := filepath.Join(policyDir, "browser-keyring-65534.json")
	if err := writeRootFile(policy, []byte("{}\n"), 0644, false); err != nil {
		t.Fatal(err)
	}
	if err := publicSystemDirectory(policyDir); err != nil {
		t.Fatal(err)
	}
	if _, err := ordinaryRun("/bin/sh", "-c", `test -r "$1" && ! test -r "$2" && ! test -x "$3"`, "sh", policy, secret, credentials); err != nil {
		t.Fatal("public policy/private credential boundary failed", err)
	}
	for path, mode := range map[string]os.FileMode{policyDir: 0755, credentials: 0700, secret: 0600, policy: 0644} {
		info, err := os.Stat(path)
		if err != nil || info.Mode().Perm() != mode {
			t.Fatalf("wrong mode at %s: %v %v", path, info, err)
		}
	}
	service := filepath.Join(root, "fixture.service")
	if err := writeManagedFile(service, []byte("# Generated by shiki-install\n"), 0644); err != nil {
		t.Fatal(err)
	}
	if info, err := os.Stat(service); err != nil || info.Mode().Perm() != 0644 {
		t.Fatal("managed service file mode was filtered by umask", err)
	}
	// Unsafe objects cannot be made trusted by a repair operation.
	link := filepath.Join(root, "linked")
	if err := os.Symlink(credentials, link); err != nil {
		t.Fatal(err)
	}
	if err := publicSystemDirectory(link); err == nil {
		t.Fatal("followed a symlink during permission repair")
	}
	unowned := filepath.Join(root, "unowned")
	if err := os.Mkdir(unowned, 0700); err != nil {
		t.Fatal(err)
	}
	if err := os.Chown(unowned, 65534, 65534); err != nil {
		t.Fatal(err)
	}
	if err := publicSystemDirectory(unowned); err == nil {
		t.Fatal("repaired an untrusted owner")
	}
	shared := filepath.Join(root, "shared")
	if err := os.Mkdir(shared, 0700); err != nil {
		t.Fatal(err)
	}
	application := filepath.Join(shared, "application")
	if err := publicSystemDirectory(application); err == nil {
		t.Fatal("public repair accepted a restrictive shared ancestor")
	}
	if _, err := publicSupportDirectoryState([]string{application}); err == nil {
		t.Fatal("current-state check hid a restrictive shared ancestor")
	}
	if info, err := os.Stat(shared); err != nil || info.Mode().Perm() != 0700 {
		t.Fatal("repair broadened existing shared directory", err)
	}
	if err := os.Chmod(shared, 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.Mkdir(application, 0700); err != nil {
		t.Fatal(err)
	}
	if current, err := publicSupportDirectoryState([]string{application}); err != nil || current {
		t.Fatal("restricted application directory should remain repairable and pending", current, err)
	}
	if err := publicSystemDirectory(application); err != nil {
		t.Fatal(err)
	}
	if current, err := publicSupportDirectoryState([]string{application}); err != nil || !current {
		t.Fatal("repaired application directory should be current", current, err)
	}
}

func TestKeyringFailureStatusDoesNotCopyChildOutput(t *testing.T) {
	status := keyringServiceStatus([]byte("Result=exit-code\nExecMainCode=1\nExecMainStatus=203\nStandardError=password-fixture\nExecMainStatus=bad value\n"))
	if !strings.Contains(status, "ExecMainStatus=203") || !strings.Contains(status, "Result=exit-code") || strings.Contains(status, "fixture") || strings.Contains(status, "bad value") {
		t.Fatalf("unsafe or missing diagnostic metadata: %s", status)
	}
}

//go:build linux

package install

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

const regionDaemonDropIn = "/etc/systemd/system/shiki-daemon.service.d/50-shikigami-region.conf"

func regionDaemonServicePolicy(uid int) []byte {
	return []byte(fmt.Sprintf("# Generated by shiki-install. Region helper authorization for UID %d.\n# Only the separately installed six-action sudoers grant authorizes root work.\n[Service]\nNoNewPrivileges=false\n", uid))
}

// The optional region grant is the sole reason to relax the core unit's
// no-new-privileges restriction. Never apply it to an unrelated service/user.
func checkRegionDaemonUnit(data []byte, user string) error {
	section, users := "", 0
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if strings.HasPrefix(line, "[") {
			section = line
			continue
		}
		if section == "[Service]" && strings.HasPrefix(line, "User=") {
			users++
			if strings.TrimPrefix(line, "User=") != user {
				return errors.New("managed daemon belongs to another user; region service policy was not applied")
			}
		}
	}
	if users != 1 {
		return errors.New("managed daemon user is ambiguous; region service policy was not applied")
	}
	return nil
}

func inspectRegionDaemonPolicy(user string, uid int) (bool, error) {
	data, exists, err := readManagedFile(ServicePath("daemon", ""))
	if err != nil {
		return false, err
	}
	if exists {
		if err = trustedInstalledFile(ServicePath("daemon", ""), 0644); err != nil {
			return false, err
		}
		if err = checkRegionDaemonUnit(data, user); err != nil {
			return false, err
		}
	}
	policy, present, err := readManagedFile(regionDaemonDropIn)
	if err != nil {
		return false, err
	}
	if present {
		if err = trustedInstalledFile(regionDaemonDropIn, 0644); err != nil {
			return false, err
		}
		if !bytes.Equal(policy, regionDaemonServicePolicy(uid)) {
			return false, errors.New("region daemon service policy was edited or belongs to another UID; preserve it for administrator review")
		}
	}
	return exists, nil
}

func installRegionDaemonPolicy(ctx context.Context, user string, uid int) error {
	exists, err := inspectRegionDaemonPolicy(user, uid)
	if err != nil {
		return err
	}
	if err = publicSystemDirectory(filepath.Dir(regionDaemonDropIn)); err != nil {
		return err
	}
	if err = writeRootFile(regionDaemonDropIn, regionDaemonServicePolicy(uid), 0644, true); err != nil {
		return err
	}
	if err = extensionRun(ctx, "", "/usr/bin/systemctl", "daemon-reload"); err != nil {
		return err
	}
	if !exists {
		return nil
	}
	restart, err := regionDaemonNeedsRestart(ctx, user)
	if err != nil {
		return err
	}
	if restart {
		if err = extensionRun(ctx, "", "/usr/bin/systemctl", "try-restart", "shiki-daemon.service"); err != nil {
			return err
		}
		restart, err = regionDaemonNeedsRestart(ctx, user)
		if err != nil {
			return err
		}
		if restart {
			return errors.New("managed daemon still blocks the authorized region helper after restart")
		}
	}
	return nil
}

func regionDaemonNeedsRestart(ctx context.Context, user string) (bool, error) {
	output, err := extensionCommand(ctx, "", "/usr/bin/systemctl", "show", "shiki-daemon.service", "--property=User", "--property=NoNewPrivileges", "--property=MainPID")
	if err != nil {
		return false, err
	}
	var actualUser, noNewPrivileges, pid string
	for _, line := range strings.Split(string(output), "\n") {
		key, value, _ := strings.Cut(line, "=")
		switch key {
		case "User":
			actualUser = value
		case "NoNewPrivileges":
			noNewPrivileges = value
		case "MainPID":
			pid = value
		}
	}
	if actualUser != user || noNewPrivileges != "no" {
		return false, errors.New("effective daemon service policy blocks the authorized region helper; inspect administrator systemd overrides")
	}
	// NoNewPrivileges is inherited by already-running children; daemon-reload
	// alone cannot repair it. Restart only if the live daemon still has it set.
	if pid == "0" {
		return false, nil
	}
	number, err := strconv.Atoi(pid)
	if err != nil || number <= 0 {
		return false, errors.New("cannot identify the managed daemon process")
	}
	status, err := os.ReadFile(filepath.Join("/proc", pid, "status"))
	if errors.Is(err, os.ErrNotExist) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	for _, line := range strings.Split(string(status), "\n") {
		if strings.HasPrefix(line, "NoNewPrivs:") {
			switch strings.TrimSpace(strings.TrimPrefix(line, "NoNewPrivs:")) {
			case "1":
				return true, nil
			case "0":
				return false, nil
			}
		}
	}
	return false, errors.New("cannot verify the managed daemon no-new-privileges status")
}

func removeRegionDaemonPolicy(uid int) error {
	data, exists, err := readManagedFile(regionDaemonDropIn)
	if err != nil || !exists {
		return err
	}
	if err = trustedInstalledFile(regionDaemonDropIn, 0644); err != nil {
		return err
	}
	if !bytes.Equal(data, regionDaemonServicePolicy(uid)) {
		return errors.New("edited region daemon service policy preserved for administrator review")
	}
	return os.Remove(regionDaemonDropIn)
}

func unitQuote(s string) (string, error) {
	if strings.ContainsAny(s, "\x00\r\n") {
		return "", errors.New("service values cannot contain control characters")
	}
	s = strings.ReplaceAll(s, "%", "%%")
	s = strings.ReplaceAll(s, "\\", "\\\\")
	s = strings.ReplaceAll(s, "\"", "\\\"")
	return "\"" + s + "\"", nil
}
func RenderService(plan Plan, prefix string) ([]byte, error) {
	executable := filepath.Join(prefix, "current", "shiki-agent")
	args := []string{executable, "--config", plan.Config}
	if plan.Role == "daemon" {
		executable = filepath.Join(prefix, "current", "shiki-daemon")
		args = []string{executable, "serve", "--config", plan.Config}
	}
	for _, value := range append(args, plan.Home, plan.Path, plan.User) {
		if _, err := unitQuote(value); err != nil {
			return nil, err
		}
	}
	if plan.Role == "client" && runtime.GOOS == "darwin" {
		var b strings.Builder
		b.WriteString("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<!DOCTYPE plist PUBLIC \"-//Apple//DTD PLIST 1.0//EN\" \"http://www.apple.com/DTDs/PropertyList-1.0.dtd\">\n<!-- Generated by shiki-install -->\n<plist version=\"1.0\"><dict>\n<key>Label</key><string>dev.shikigami.agent</string>\n<key>ProgramArguments</key><array>")
		escape := func(s string) { xml.EscapeText(&b, []byte(s)) }
		for _, arg := range args {
			b.WriteString("<string>")
			escape(arg)
			b.WriteString("</string>")
		}
		b.WriteString("</array>\n<key>EnvironmentVariables</key><dict><key>HOME</key><string>")
		escape(plan.Home)
		b.WriteString("</string><key>PATH</key><string>")
		escape(plan.Path)
		b.WriteString("</string></dict>\n<key>WorkingDirectory</key><string>")
		escape(plan.Home)
		b.WriteString("</string>\n<key>RunAtLoad</key><true/>\n<key>KeepAlive</key><dict><key>SuccessfulExit</key><false/></dict>\n<key>Umask</key><integer>63</integer>\n</dict></plist>\n")
		return []byte(b.String()), nil
	}
	quoted := make([]string, len(args))
	for i, arg := range args {
		quoted[i], _ = unitQuote(strings.ReplaceAll(arg, "$", "$$"))
	}
	home, _ := unitQuote("HOME=" + plan.Home)
	path, _ := unitQuote("PATH=" + plan.Path)
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by shiki-install\n[Unit]\nDescription=Shikigami %s\nAfter=network-online.target\nWants=network-online.target\n\n[Service]\nType=simple\n", plan.Role)
	if plan.Role == "daemon" {
		if plan.User == "" || strings.ContainsAny(plan.User, " \t\r\n%/\\=") {
			return nil, errors.New("invalid daemon service user")
		}
		fmt.Fprintf(&b, "User=%s\n", plan.User)
	}
	// WorkingDirectory does not parse shell-style quotes like ExecStart does.
	// systemd's '~' selects the User= account home (or the user manager's home).
	fmt.Fprintf(&b, "Environment=%s\nEnvironment=%s\nWorkingDirectory=~\nExecStart=%s\nRestart=on-failure\nRestartSec=5s\nTimeoutStopSec=15s\nUMask=0077\nNoNewPrivileges=true\nStandardOutput=journal\nStandardError=journal\n", home, path, strings.Join(quoted, " "))
	if plan.Role == "daemon" {
		b.WriteString("KillMode=process\nPrivateTmp=false\n")
	} else {
		b.WriteString("KillMode=control-group\n")
	}
	target := "default.target"
	if plan.Role == "daemon" {
		target = "multi-user.target"
	}
	fmt.Fprintf(&b, "\n[Install]\nWantedBy=%s\n", target)
	return []byte(b.String()), nil
}
func ServicePath(role, home string) string {
	if role == "daemon" {
		return "/etc/systemd/system/shiki-daemon.service"
	}
	if runtime.GOOS == "darwin" {
		return filepath.Join(home, "Library", "LaunchAgents", "dev.shikigami.agent.plist")
	}
	return filepath.Join(home, ".config", "systemd", "user", "shiki-agent.service")
}
func launchDomain(uid int) string { return "gui/" + strconv.Itoa(uid) }

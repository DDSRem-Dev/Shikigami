#!/usr/bin/env python3
"""Remove only the opt-in test's own standard LaunchAgent and runtime tree users."""
import os
import pathlib
import plistlib
import pwd
import signal
import subprocess
import sys
import time

root = pathlib.Path(sys.argv[1])
if root.parent != pathlib.Path('/private/tmp') or not root.name.startswith('shiki-launchd.'):
    raise SystemExit('Refusing an unexpected cleanup root')
account = pwd.getpwuid(os.getuid())
plist = pathlib.Path(account.pw_dir) / 'Library/LaunchAgents/dev.shikigami.agent.plist'
program = str(root / 'runtime/install/current/shiki-agent')
domain = f'gui/{os.getuid()}'
target = domain + '/dev.shikigami.agent'

def job():
    return subprocess.run(['/bin/launchctl', 'print', target], capture_output=True, text=True, timeout=10)

state = job()
owned = False
if plist.exists() or plist.is_symlink():
    if plist.is_symlink():
        raise SystemExit('Refusing a symlink service file')
    with plist.open('rb') as stream:
        value = plistlib.load(stream)
    owned = value.get('ProgramArguments', [None])[0] == program
if state.returncode == 0 and f'program = {program}\n' in state.stdout:
    subprocess.run(['/bin/launchctl', 'bootout', target], check=True, timeout=20)
elif state.returncode == 0 and owned:
    raise SystemExit('Service identity changed; refusing cleanup')
if owned:
    for _ in range(40):
        if job().returncode != 0:
            break
        time.sleep(0.25)
    else:
        raise SystemExit('Owned LaunchAgent still registered after bootout')
    plist.unlink()

# A forcibly interrupted atomic service write may leave its staging file.
# The unique program path must appear before this cleanup can attribute it.
staged = plist.with_name('.' + plist.name + '.install')
if staged.exists() and not staged.is_symlink() and staged.stat().st_size <= 65536:
    data = staged.read_bytes()
    if len(data) <= 65536 and b'Generated by shiki-install' in data and program.encode() in data:
        staged.unlink()

def owned_processes():
    output = subprocess.check_output(['/bin/ps', '-axo', 'pid=,command='], text=True)
    result = []
    for line in output.splitlines():
        fields = line.split()
        if len(fields) < 2 or not fields[1].startswith(str(root / 'runtime') + '/'):
            continue
        executable = pathlib.Path(fields[1])
        if executable.name not in ('shiki-agent', 'shiki-plugin-sync', 'shiki-plugin-port'):
            continue
        result.append(int(fields[0]))
    return result

# Only processes whose executable argument is inside this unique private test
# tree are eligible. This fallback is cleanup, never a plugin-reaping pass claim.
for sig in (signal.SIGTERM, signal.SIGKILL):
    remaining = owned_processes()
    if not remaining:
        break
    print(f'Cleanup fallback: signal {sig} to owned remaining PIDs {remaining}')
    for pid in remaining:
        if pid in owned_processes():
            try:
                os.kill(pid, sig)
            except ProcessLookupError:
                pass
    for _ in range(20):
        if not owned_processes():
            break
        time.sleep(0.25)
if owned_processes():
    raise SystemExit('Owned processes remain; keep temporary files for inspection')
print('LaunchAgent cleanup: owned job/plist removed or already absent; unrelated services preserved')
